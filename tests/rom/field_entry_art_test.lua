-- ROM-conformance facts for the generated field-entry class: the real private
-- dump compiles the nine map-name banner skins and the 76 unique location
-- preview composites, every selected source triple renders the compiled PNG,
-- the output is deterministic, and publication reads ready. Asserts only
-- non-copyright structural facts. Source selection follows
-- the retail ROM's area-icon loading (NARC163
-- char member 2*i, palette 2*i+1, source tiles 1..68 in a 17x4 grid) and
-- map-preview graphic order (NARC150 triples base NCLR, base+1 NCGR, base+2 NSCR).

local Assert = require("tests.support.Assert")
local CacheFs = require("libs.storage.src.CacheFs")
local PngReader = require("tests.support.PngReader")
local FieldEntryAssetCompiler = require("romdump.src.digest.ui.FieldEntryAssetCompiler")
local FieldEntryCacheWriter = require("romdump.src.digest.ui.FieldEntryCacheWriter")
local FieldEntryAssetCache = require("libs.assets.src.field.FieldEntryAssetCache")
local G2dDecoder = require("romdump.src.digest.ui.G2dDecoder")
local G2dRasterizer = require("romdump.src.digest.ui.G2dRasterizer")
local Lz10 = require("romdump.src.digest.Lz10")
local Hashing = require("romdump.src.digest.Hashing")
local MapCatalog = require("romdump.src.digest.map.MapCatalog")
local FieldEntryFixture = require("tests.support.FieldEntryFixture")

local T = {}

local AREA_WINDOWS_ALIAS = "field_area_windows"
local PREVIEWS_ALIAS = "field_map_previews"

-- Read one NARC member, unwrapping the LZ10 wrapper the dump uses.
local function memberBytes(romFs, alias, memberId)
  local archive = assert(romFs:openNarc(alias))
  local bytes = assert(archive:readMember(memberId))
  if string.byte(bytes, 1) == 0x10 then
    local plain, err = Lz10.decode(bytes)
    assert(plain, err and err.message)
    return plain
  end
  return bytes
end

-- The banner composes source tiles 1..68 as a 17x4 grid in palette bank 0
-- with no flips, matching the retail copy from the NCGR tile run.
local function bannerScreen()
  local entries = {}
  for index, tile in ipairs(FieldEntryFixture.bannerEntries()) do
    entries[index] = { tile = tile, palette = 0, flipH = false, flipV = false }
  end
  return { width = 136, height = 32, entries = entries }
end

-- The expected banner pixels and decoded NCLR for one style, computed
-- independently from the selected source members.
local function expectedBanner(romFs, style)
  local char =
    assert(G2dDecoder.decodeChar(memberBytes(romFs, AREA_WINDOWS_ALIAS, style * 2), { label = "banner char" }))
  local palette =
    assert(G2dDecoder.decodePalette(memberBytes(romFs, AREA_WINDOWS_ALIAS, style * 2 + 1), { label = "banner palette" }))
  local image = G2dRasterizer.renderScreen(char, { colors = palette.colors }, bannerScreen(), {
    asset = "banner expectation",
  })
  return image.pixels, palette.colors
end

-- The expected preview pixels for one source triple base: palette member
-- `base`, char member `base + 1`, screen member `base + 2`, with palette
-- index 0 kept as the opaque MAIN BG2 backdrop.
local function expectedPreview(romFs, base)
  local palette =
    assert(G2dDecoder.decodePalette(memberBytes(romFs, PREVIEWS_ALIAS, base), { label = "preview palette" }))
  local char = assert(G2dDecoder.decodeChar(memberBytes(romFs, PREVIEWS_ALIAS, base + 1), { label = "preview char" }))
  local screen =
    assert(G2dDecoder.decodeScreen(memberBytes(romFs, PREVIEWS_ALIAS, base + 2), { label = "preview screen" }))
  local image = G2dRasterizer.renderScreen(char, { colors = palette.colors }, screen, {
    asset = "preview expectation",
  }, { backdrop = true })
  return image.pixels
end

local function pngPixels(bundle, key)
  local entry = assert(bundle.manifest.assets[key], "the manifest indexes asset " .. tostring(key))
  local bytes = assert(bundle.assets[entry.image], "the asset carries generated bytes: " .. tostring(entry.image))
  local width, height, rgba = PngReader.rgba(bytes)
  return width, height, rgba
end

-- The compiled class is fully ready and deterministic against the real dump.
function T.compiled_entry_assets_are_ready_and_stable(romFs, version)
  local cache = CacheFs.forVersion(version)
  local bundle = assert(FieldEntryAssetCompiler.compile(romFs))
  local marker = FieldEntryAssetCache.marker(romFs:metadata().sha1, Hashing.hashLua(bundle.dependencies))
  Assert.equal(bundle.marker, marker, "the marker is FORMAT:romSha1:depHash")
  Assert.isTrue(FieldEntryAssetCache.validateManifest(bundle.manifest), "the compiled manifest validates")

  Assert.equal(bundle.manifest.reference.width, 256)
  Assert.equal(bundle.manifest.reference.height, 192)
  for style = 0, FieldEntryFixture.BANNER_STYLE_COUNT - 1 do
    Assert.notNil(bundle.manifest.bannerStyles[style], "the manifest carries banner style " .. style)
    Assert.notNil(bundle.manifest.bannerTextPalettes[style], "the manifest carries text roles for style " .. style)
  end

  -- The banner style map is retail banner eligibility: buildings carry no
  -- style so the runtime controller gates on membership alone.
  local maps = require("romdump.src.catalog.hgss.maps").byId
  for id in pairs(bundle.manifest.bannerStyleByMapId) do
    local record = assert(maps[id], "a banner style names a frozen map header")
    Assert.isTrue(
      record.mapType ~= "INTERIOR" and record.mapType ~= "POKEMON_CENTER",
      "no building map header carries a banner style: " .. tostring(record.symbol)
    )
  end
  local buildingId = assert(MapCatalog.idForSymbol("MAP_NEW_BARK_PLAYER_HOUSE_1F"))
  Assert.isTrue(maps[buildingId].areaIcon ~= 0, "the sampled building carries an area icon")
  Assert.isNil(bundle.manifest.bannerStyleByMapId[buildingId], "an interior building is suppressed")

  -- Recompiling is deterministic and the published class is fully ready.
  local second = assert(FieldEntryAssetCompiler.compile(romFs))
  Assert.equal(second.marker, bundle.marker)
  FieldEntryCacheWriter.write(cache, bundle)
  Assert.isTrue(FieldEntryAssetCache.isReady(cache, bundle.marker), "every indexed file is ready after publication")
  Assert.isFalse(FieldEntryAssetCache.isReady(cache, bundle.marker .. "-stale"))
end

-- Every one of the nine banner skins decodes its own source char/palette
-- pair, composes the 17x4 grid, and publishes the source text color roles.
function T.banner_skins_match_the_selected_source_members(romFs, _)
  local bundle = assert(FieldEntryAssetCompiler.compile(romFs))
  local seen = {}
  for style = 0, FieldEntryFixture.BANNER_STYLE_COUNT - 1 do
    local expected, colors = expectedBanner(romFs, style)
    local width, height, rgba = pngPixels(bundle, bundle.manifest.bannerStyles[style])
    Assert.equal(width, 136, "banner style " .. style .. " width")
    Assert.equal(height, 32, "banner style " .. style .. " height")
    Assert.equal(rgba, expected, "banner style " .. style .. " pixels follow the source 17x4 grid")
    Assert.isNil(seen[rgba], "banner style " .. style .. " renders distinct artwork")
    seen[rgba] = true

    local roles = assert(bundle.manifest.bannerTextPalettes[style])
    Assert.deepEqual(roles.foreground, { r = colors[2].r, g = colors[2].g, b = colors[2].b }, "style " .. style .. " foreground")
    Assert.deepEqual(roles.shadow, { r = colors[3].r, g = colors[3].g, b = colors[3].b }, "style " .. style .. " shadow")
    Assert.deepEqual(roles.background, { r = colors[1].r, g = colors[1].g, b = colors[1].b }, "style " .. style .. " background")
  end
end

-- The exact 25 x four source selection, deduped to 76 unique preview
-- composites, and time/alias identity preserved across duplicate triples and
-- shared map headers.
function T.preview_inventory_matches_the_selected_source_triples(romFs, _)
  local bundle = assert(FieldEntryAssetCompiler.compile(romFs))
  local distinctKeys = {}
  local distinctBytes = {}
  local destinationCount = 0
  for _, destination in ipairs(FieldEntryFixture.DESTINATIONS) do
    local mapId = assert(MapCatalog.idForSymbol(destination.symbol), destination.symbol)
    local slots = assert(bundle.manifest.previewByMapId[mapId], destination.symbol .. " carries four slots")
    destinationCount = destinationCount + 1
    for slot = 0, 3 do
      local key = assert(slots[slot], destination.symbol .. " slot " .. slot)
      distinctKeys[key] = true
      local width, height, rgba = pngPixels(bundle, key)
      Assert.equal(width, 256, destination.symbol .. " slot " .. slot .. " width")
      Assert.equal(height, 192, destination.symbol .. " slot " .. slot .. " height")
      local base = assert(destination.bases[slot + 1])
      Assert.equal(rgba, expectedPreview(romFs, base), destination.symbol .. " slot " .. slot .. " pixels")
      distinctBytes[rgba] = true
    end
  end
  Assert.equal(destinationCount, 25, "the selector carries exactly the 25 destination map ids")

  local keyCount = 0
  for _ in pairs(distinctKeys) do
    keyCount = keyCount + 1
  end
  Assert.equal(keyCount, 76, "the 25 destinations collapse to 76 unique preview images")
  local byteCount = 0
  for _ in pairs(distinctBytes) do
    byteCount = byteCount + 1
  end
  Assert.equal(byteCount, 76, "each unique preview image renders distinct pixels")
end

-- Alias edge cases: Ilex Forest evening uses its own source graphic while
-- most caves alias evening to daytime, and alternate map headers share art.
function T.destination_alias_identity_is_preserved(romFs, _)
  local bundle = assert(FieldEntryAssetCompiler.compile(romFs))
  local function slots(symbol)
    return assert(bundle.manifest.previewByMapId[assert(MapCatalog.idForSymbol(symbol))], symbol)
  end

  Assert.isTrue(slots("MAP_ILEX_FOREST")[2] ~= slots("MAP_ILEX_FOREST")[1], "Ilex evening is a distinct key")
  local _, _, eveningRgba = pngPixels(bundle, slots("MAP_ILEX_FOREST")[2])
  local _, _, dayRgba = pngPixels(bundle, slots("MAP_ILEX_FOREST")[1])
  Assert.isTrue(eveningRgba ~= dayRgba, "Ilex evening renders distinct pixels")

  Assert.equal(slots("MAP_UNION_CAVE_1F")[2], slots("MAP_UNION_CAVE_1F")[1], "Union Cave evening aliases day")

  for _, pair in ipairs({
    { "MAP_RUINS_OF_ALPH_HALL_ENTRANCE", "MAP_RUINS_OF_ALPH_HALL_ENTRANCE_SINJOH_EVENT" },
    { "MAP_VICTORY_ROAD_1F", "MAP_VICTORY_ROAD_3F" },
  }) do
    for slot = 0, 3 do
      Assert.equal(slots(pair[1])[slot], slots(pair[2])[slot], pair[1] .. " and " .. pair[2] .. " share slot " .. slot)
    end
  end
end

return require("tests.rom.support.RomSuite").fromFacts(T)
