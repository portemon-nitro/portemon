-- CPU-only entry point for the presentation preparation worker. Reads
-- confined cache bytes, decodes/packs mesh upload buffers, decodes image
-- data, or classifies private image derivatives, and replies with flat
-- records carrying love Data/ImageData. Never touches love.graphics: GPU
-- realization stays on the main thread.
--
-- The module is resolved through the packaged require path by a small
-- literal bootstrap: the queue starts its thread from that bootstrap, which
-- installs the explicitly supplied development search path when required
-- and then calls run with the queue's channel pair. Requiring this module
-- in any other state only exposes run without starting any work.

local Worker = {}

---@param requestChannel table<string, unknown> borrowed queue request channel
---@param replyChannel table<string, unknown> borrowed queue reply channel
function Worker.run(requestChannel, replyChannel)
  assert(requestChannel and replyChannel, "preparation worker requires its request/reply channels")

  pcall(require, "love.image")

  local Errors = require("libs.errors.src.Errors")
  local CacheFs = require("libs.storage.src.CacheFs")
  local ImageDerivative = require("libs.hgss.src.presentation.ImageDerivative")
  local NativeTextureBank = require("libs.assets.src.model.NativeTextureBank")
  local SceneMesh = require("libs.hgss.src.presentation.SceneMesh")
  local TextureDecoder = require("libs.nds.src.gx.TextureDecoder")

  -- One worker-local versioned cache for every job kind. Every confined
  -- CacheFs read below reaches the current generated bytes through the
  -- standard versioned backend while logical decoding, confinement, and
  -- payload replies stay exactly as before. Lazily built on the first job
  -- so requiring this module never touches love, the filesystem, or any
  -- thread.
  local workerCacheFs = nil
  local workerVersionId = nil
  ---@param versionId string
  ---@return CacheFs
  local function cacheFor(versionId)
    assert(type(versionId) == "string" and versionId ~= "", "preparation worker requires a version identity")
    if workerCacheFs == nil then
      workerCacheFs = CacheFs.forVersion(versionId)
      workerVersionId = versionId
    elseif versionId ~= workerVersionId then
      error("preparation worker version changed mid-lifetime: " .. tostring(versionId), 0)
    end
    return workerCacheFs --[[@as CacheFs]]
  end

  local function fail(token, kind, path, cause)
    local text = Errors.is(cause) and Errors.format(cause) or tostring(cause)
    replyChannel:push({ token = token, ok = false, kind = kind, path = path, error = text })
  end

  -- Mesh bytes enter through the versioned cache so wrapped physical files
  -- decode off the main thread. The confined path travels with the request
  -- for channel compatibility, but the logical path is authoritative: it
  -- must resolve to exactly the confined path before any byte is read.
  local function readMeshBytes(versionId, logicalPath, path)
    assert(type(versionId) == "string" and versionId ~= "", "mesh preparation requires a version identity")
    assert(type(logicalPath) == "string" and logicalPath ~= "", "mesh preparation requires a logical path")
    local cache = cacheFor(versionId)
    if cache:resolve(logicalPath) ~= path then
      error("mesh preparation path escapes its confined cache entry", 0)
    end
    local bytes = cache:read(logicalPath)
    if bytes == nil then
      error("unreadable cache file: " .. tostring(path), 0)
    end
    return bytes
  end

  local function prepareMesh(token, versionId, logicalPath, path)
    local readOk, bytes = pcall(readMeshBytes, versionId, logicalPath, path)
    if not readOk then
      fail(token, "mesh", path, bytes)
      return
    end
    local ok, prepared = pcall(SceneMesh.prepareUpload, bytes, path)
    if not ok then
      fail(token, "mesh", path, prepared)
      return
    end
    replyChannel:push({
      token = token,
      ok = true,
      kind = "mesh",
      path = path,
      vertexData = prepared.vertexData,
      indexData = prepared.indexData,
      vertexCount = prepared.vertexCount,
      indexCount = prepared.indexCount,
      indexType = prepared.indexType,
      centerX = prepared.centerX,
      centerY = prepared.centerY,
      centerZ = prepared.centerZ,
      minX = prepared.minX,
      maxX = prepared.maxX,
      minY = prepared.minY,
      maxY = prepared.maxY,
      minZ = prepared.minZ,
      maxZ = prepared.maxZ,
    })
  end

  -- A generated PNG is the only persistent image asset: it is decoded here,
  -- classified into the padded/indexed upload payload, and never copied into a
  -- second on-disk derivative. Replies carry only Data plus small metadata; a
  -- missing or damaged generated PNG fails loudly instead of substituting
  -- bytes. Never touches graphics.
  local function prepareImageDerivative(token, versionId, logicalPath, path)
    local function work()
      assert(
        type(versionId) == "string" and versionId ~= "",
        "image-derivative preparation requires a version identity"
      )
      assert(
        type(logicalPath) == "string" and logicalPath ~= "",
        "image-derivative preparation requires a logical path"
      )
      local cache = cacheFor(versionId)
      if cache:resolve(logicalPath) ~= path then
        error("image-derivative preparation path escapes its confined cache entry", 0)
      end
      local pngBytes = cache:read(logicalPath)
      if pngBytes == nil then
        error("unreadable cache file: " .. tostring(path), 0)
      end
      local classified
      do
        local fileData, fileError = love.filesystem.newFileData(pngBytes, "prepared.png")
        if fileData == nil then
          error("unreadable image source: " .. tostring(path) .. ": " .. tostring(fileError), 0)
        end
        local imageData, imageError = love.image.newImageData(fileData)
        if imageData == nil then
          error("unreadable image source: " .. tostring(path) .. ": " .. tostring(imageError), 0)
        end
        classified = ImageDerivative.classify(imageData)
      end
      replyChannel:push({
        token = token,
        ok = true,
        kind = "image-derivative",
        path = path,
        pixelHash = classified.pixelHash,
        width = classified.width,
        height = classified.height,
        representation = classified.kind,
        colors = classified.colors,
        indexData = classified.indexData,
        paletteData = classified.paletteData,
      })
    end
    local ok, err = pcall(work)
    if not ok then
      fail(token, "image-derivative", path, err)
    end
  end

  -- One draw of a native model bank, decoded and packed for upload: the draw's
  -- command bytes replay through the shared GX decoder, every terrain-eligible
  -- sibling of the same bank is decoded and repaired with it once, and the
  -- result is the existing upload packet. No ROM source and no GPU object.
  local function prepareNativeMesh(token, versionId, logicalPath, path, selector)
    local function work()
      assert(
        type(selector) == "table" and type(selector.drawIndex) == "number",
        "native mesh preparation requires a draw selector"
      )
      local cache = cacheFor(versionId)
      if cache:resolve(logicalPath) ~= path then
        error("native mesh preparation path escapes its confined cache entry", 0)
      end
      local bytes = cache:read(logicalPath)
      if bytes == nil then
        error("unreadable cache file: " .. tostring(path), 0)
      end
      return SceneMesh.prepareNativeBank(bytes, selector, path)
    end
    local ok, prepared = pcall(work)
    if not ok then
      fail(token, "g4gx", path, prepared)
      return
    end
    replyChannel:push({
      token = token,
      ok = true,
      kind = "mesh",
      path = path,
      vertexData = prepared.vertexData,
      indexData = prepared.indexData,
      vertexCount = prepared.vertexCount,
      indexCount = prepared.indexCount,
      indexType = prepared.indexType,
      centerX = prepared.centerX,
      centerY = prepared.centerY,
      centerZ = prepared.centerZ,
      minX = prepared.minX,
      maxX = prepared.maxX,
      minY = prepared.minY,
      maxY = prepared.maxY,
      minZ = prepared.minZ,
      maxZ = prepared.maxZ,
    })
  end

  -- One named texture/palette pair of a native texture bank: the compact
  -- source texels decode straight to RGBA in this worker, then classify into
  -- the same upload payload the PNG path produces. The palette is selected by
  -- name, never baked into the perspective of one material.
  local function prepareNativeTexture(token, versionId, logicalPath, path, selector)
    local function work()
      assert(
        type(selector) == "table" and type(selector.textureName) == "string",
        "native texture preparation requires a named texture"
      )
      local cache = cacheFor(versionId)
      if cache:resolve(logicalPath) ~= path then
        error("native texture preparation path escapes its confined cache entry", 0)
      end
      local bytes = cache:read(logicalPath)
      if bytes == nil then
        error("unreadable cache file: " .. tostring(path), 0)
      end
      local bank, bankError = NativeTextureBank.read(bytes)
      if bank == nil then
        error(bankError, 0)
      end
      local texture = bank:texture(selector.textureName)
      if texture == nil then
        error("texture bank has no texture " .. tostring(selector.textureName) .. ": " .. tostring(path), 0)
      end
      local palette = nil
      if selector.paletteName ~= nil then
        palette = bank:palette(selector.paletteName)
        if palette == nil then
          error("texture bank has no palette " .. tostring(selector.paletteName) .. ": " .. tostring(path), 0)
        end
      end
      local opts = {
        format = texture.formatRaw,
        width = texture.width,
        height = texture.height,
        color0Transparent = texture.color0Transparent,
        texel = texture.texels,
        palette = palette and palette.data or "",
      }
      if texture.indexData ~= nil then
        opts.indexData = texture.indexData
      end
      local rgba = love.data.newByteData(texture.width * texture.height * 4)
      local rgbaSize = rgba:getSize()
      ---@cast rgbaSize integer
      TextureDecoder.decodeInto(opts, rgba:getFFIPointer(), rgbaSize, TextureDecoder.newScratch(), {
        name = texture.name,
      })
      local imageData = love.image.newImageData(texture.width, texture.height, "rgba8", rgba --[[@as string]])
      return ImageDerivative.classify(imageData)
    end
    local ok, classified = pcall(work)
    if not ok then
      fail(token, "g4tx", path, classified)
      return
    end
    replyChannel:push({
      token = token,
      ok = true,
      kind = "image-derivative",
      path = path,
      pixelHash = classified.pixelHash,
      width = classified.width,
      height = classified.height,
      representation = classified.kind,
      colors = classified.colors,
      indexData = classified.indexData,
      paletteData = classified.paletteData,
    })
  end

  -- Sample payloads travel as one transferable ByteData built from the
  -- versioned PCM16LE bytes, without assembling Lua sample tables and
  -- without touching graphics. The confined path travels with the request
  -- for channel compatibility, but the logical path is authoritative: it
  -- must resolve to exactly the confined path before any byte is read.
  local function prepareAudioSample(token, versionId, logicalPath, path)
    local function work()
      assert(type(versionId) == "string" and versionId ~= "", "audio-sample preparation requires a version identity")
      assert(type(logicalPath) == "string" and logicalPath ~= "", "audio-sample preparation requires a logical path")
      local cache = cacheFor(versionId)
      if cache:resolve(logicalPath) ~= path then
        error("audio-sample preparation path escapes its confined cache entry", 0)
      end
      local bytes = cache:read(logicalPath)
      if type(bytes) ~= "string" or #bytes == 0 or #bytes % 2 ~= 0 then
        error("unreadable audio sample payload: " .. tostring(path), 0)
      end
      local byteData = love.data.newByteData(bytes)
      replyChannel:push({
        token = token,
        ok = true,
        kind = "audio-sample",
        path = path,
        byteData = byteData,
        size = #bytes,
      })
    end
    local ok, err = pcall(work)
    if not ok then
      fail(token, "audio-sample", path, err)
    end
  end

  -- Plain images travel through the same confined versioned cache as every
  -- other job kind, so the PNG decode and the reply shape stay exactly as
  -- before.
  local function prepareImage(token, versionId, logicalPath, path)
    local function work()
      assert(type(versionId) == "string" and versionId ~= "", "image preparation requires a version identity")
      assert(type(logicalPath) == "string" and logicalPath ~= "", "image preparation requires a logical path")
      local cache = cacheFor(versionId)
      if cache:resolve(logicalPath) ~= path then
        error("image preparation path escapes its confined cache entry", 0)
      end
      local bytes = cache:read(logicalPath)
      if bytes == nil then
        error("unreadable cache file: " .. tostring(path), 0)
      end
      local fileData, fileError = love.filesystem.newFileData(bytes, "prepared.png")
      if fileData == nil then
        error("unreadable image source: " .. tostring(path) .. ": " .. tostring(fileError), 0)
      end
      local imageData, imageError = love.image.newImageData(fileData)
      if imageData == nil then
        error("unreadable image source: " .. tostring(path) .. ": " .. tostring(imageError), 0)
      end
      return imageData
    end
    local ok, imageData = pcall(work)
    if not ok then
      fail(token, "image", path, imageData)
      return
    end
    replyChannel:push({ token = token, ok = true, kind = "image", path = path, imageData = imageData })
  end

  while true do
    local job = requestChannel:demand()
    if type(job) ~= "table" or job.op == "shutdown" then
      break
    end
    if job.op == "prepare" and job.kind == "mesh" then
      local ok, err = pcall(prepareMesh, job.token, job.versionId, job.logicalPath, job.path)
      if not ok then
        fail(job.token, job.kind, job.path, err)
      end
    elseif job.op == "prepare" and job.kind == "image" then
      local ok, err = pcall(prepareImage, job.token, job.versionId, job.logicalPath, job.path)
      if not ok then
        fail(job.token, job.kind, job.path, err)
      end
    elseif job.op == "prepare" and job.kind == "image-derivative" then
      local ok, err = pcall(prepareImageDerivative, job.token, job.versionId, job.logicalPath, job.path)
      if not ok then
        fail(job.token, job.kind, job.path, err)
      end
    elseif job.op == "prepare" and job.kind == "g4gx" then
      local ok, err = pcall(prepareNativeMesh, job.token, job.versionId, job.logicalPath, job.path, job.selector)
      if not ok then
        fail(job.token, job.kind, job.path, err)
      end
    elseif job.op == "prepare" and job.kind == "g4tx" then
      local ok, err = pcall(prepareNativeTexture, job.token, job.versionId, job.logicalPath, job.path, job.selector)
      if not ok then
        fail(job.token, job.kind, job.path, err)
      end
    elseif job.op == "prepare" and job.kind == "audio-sample" then
      local ok, err = pcall(prepareAudioSample, job.token, job.versionId, job.logicalPath, job.path)
      if not ok then
        fail(job.token, job.kind, job.path, err)
      end
    else
      fail(job.token, job.kind, job.path, "unknown preparation request")
    end
  end
end

-- A directly started thread entry carries its channels as chunk arguments;
-- a plain require carries the module name instead and only exposes run.
local directRequest, directReply = ...
if type(directRequest) == "table" and type(directReply) == "table" then
  Worker.run(directRequest, directReply)
end

return Worker
