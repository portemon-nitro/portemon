-- Staged damage preview matching CalcMoveDamage
-- (src/battle/overlay_12_0224E4FC.c): base stats with staged application,
-- power/attack/defense ability and item modifiers, pinch abilities, burn,
-- screens, and the staged base formula. Unmapped facts (held-item
-- modifiers, Slow Start clock, Rivalry genders, unmodeled clocks) fail
-- closed when their branches are reached.
---@param state TrainerAiProgramState command state under execution
---@param moveId integer numeric move identity under preview
---@param power integer working move power under preview
---@param moveType integer working move type under preview
---@param category integer working move category 0/1/2 under preview
---@return integer staged base damage under the native formula
local function calcPreview(state, moveId, power, moveType, category)
  local facts = state.facts --[[@as table<string, unknown>]]
  local atk = facts.atk --[[@as integer]]
  local tgt = facts.tgt --[[@as integer]]
  local attacker = battlerFacts(state, atk)
  local target = battlerFacts(state, tgt)
  local abilityA = attacker.ability --[[@as integer]]
  local abilityT = target.ability --[[@as integer]]
  local atkStages = attacker.stages --[[@as table<integer, integer>]]
  local defStages = target.stages --[[@as table<integer, integer>]]
  local monAtk = attacker.atk --[[@as integer]]
  local monDef = target.def --[[@as integer]]
  local monSpa = attacker.spa --[[@as integer]]
  local monSpd = target.spd --[[@as integer]]
  -- The preview runs outside action execution, where the revenge power
  -- multiplier rests at its reset value.
  local movePower = math.floor((power * 10) / 10)
  if abilityA == 96 then
    moveType = 0
  end
  if abilityA == 101 and moveId ~= 165 and movePower <= 60 then
    movePower = math.floor((movePower * 15) / 10)
  end
  if abilityA == 37 or abilityA == 74 then
    monAtk = monAtk * 2
  end
  if abilityA == 112 then
    error(BattleErrors.missingBehavior("trainer evaluation reads its slow start", {}))
  end
  local itemA = attacker.item --[[@as integer]]
  local itemT = target.item --[[@as integer]]
  local held = facts.heldEffects --[[@as table<integer, integer>]]
  local modA = facts.heldMods --[[@as table<integer, integer>]]
  local effA = 0
  local effT = 0
  if itemA ~= 0 then
    local resolved = held[itemA]
    if resolved == nil then
      error(BattleErrors.missingBehavior("trainer evaluation reads its held item facts", { item = itemA }))
    end
    effA = resolved
  end
  if itemT ~= 0 then
    local resolved = held[itemT]
    if resolved == nil then
      error(BattleErrors.missingBehavior("trainer evaluation reads its held item facts", { item = itemT }))
    end
    effT = resolved
  end
  local attackerSpecies = attacker.species --[[@as string?]]
  local targetSpecies = target.species --[[@as string?]]
  if effA ~= 0 then
    local boosted = TYPE_BOOSTS[effA]
    if boosted ~= nil then
      if boosted == moveType then
        local mod = modA[itemA]
        if mod == nil then
          error(BattleErrors.missingBehavior("trainer evaluation reads its held modifier", { item = itemA }))
        end
        movePower = math.floor((movePower * (100 + mod)) / 100)
      end
    elseif effA == 55 then
      monAtk = math.floor((monAtk * 150) / 100)
    elseif effA == 125 then
      monSpa = math.floor((monSpa * 150) / 100)
    elseif effA == 60 then
      -- Soul Dew raises the special attack of its own Latios/Latias
      -- bearers. Evaluation battles never carry the frontier bit
      -- (battleType is 1 or 3), so the frontier exclusion never
      -- triggers and the rule applies unconditionally.
      if attackerSpecies == "LATIOS" or attackerSpecies == "LATIAS" then
        monSpa = math.floor((monSpa * 150) / 100)
      end
    elseif effA == 61 then
      -- DeepSeaTooth doubles the special attack of its Clamperl bearer.
      if attackerSpecies == "CLAMPERL" then
        monSpa = monSpa * 2
      end
    elseif effA == 71 then
      -- Light Ball doubles the move power of its Pikachu bearer.
      if attackerSpecies == "PIKACHU" then
        movePower = movePower * 2
      end
    elseif effA == 91 then
      -- Thick Club doubles the attack of its Cubone/Marowak bearers.
      if attackerSpecies == "CUBONE" or attackerSpecies == "MAROWAK" then
        monAtk = monAtk * 2
      end
    elseif effA == 62 or effA == 90 then
      -- Defender-side items held by the attacker read no adjustment
      -- here; the defender arms below apply them from the defender
      -- record.
    elseif effA == 3 or effA == 4 or effA == 2 then
      error(BattleErrors.missingBehavior("trainer evaluation reads its orb item", { item = itemA }))
    elseif effA == 94 or effA == 95 then
      local mod = modA[itemA]
      if mod == nil then
        error(BattleErrors.missingBehavior("trainer evaluation reads its held modifier", { item = itemA }))
      end
      if (effA == 94 and category == 0) or (effA == 95 and category == 1) then
        movePower = math.floor((movePower * (100 + mod)) / 100)
      end
    elseif effA == 13 then
      -- Health-restore berries never adjust staged damage: the source
      -- damage calculation reads no berry hold effects, so the preview
      -- leaves power untouched.
    elseif effA == 1 or effA == 6 or effA == 12 or effA == 21 or effA == 33 or effA == 49 or effA == 109 then
      -- Exactly these seven effects read no adjustment in the damage
      -- estimate: neither the damage calculation nor the type pipeline
      -- branches on them, so the preview leaves power and stats
      -- untouched. Every other unmapped effect stays fail-closed below.
    elseif effA ~= 0 then
      error(BattleErrors.missingBehavior("trainer evaluation reads its held item facts", { item = itemA }))
    end
  end
  if effT == 60 then
    -- Soul Dew raises the special defense of its own Latios/Latias
    -- targets; the frontier exclusion never triggers here either.
    if targetSpecies == "LATIOS" or targetSpecies == "LATIAS" then
      monSpd = math.floor((monSpd * 150) / 100)
    end
  elseif effT == 62 then
    -- DeepSeaScale doubles the special defense of its Clamperl target.
    if targetSpecies == "CLAMPERL" then
      monSpd = monSpd * 2
    end
  elseif effT == 90 then
    -- Metal Powder doubles the defense of its Ditto target.
    if targetSpecies == "DITTO" then
      monDef = monDef * 2
    end
  end
  if abilityA == 55 then
    monAtk = math.floor((monAtk * 150) / 100)
  end
  if abilityA == 62 and attacker.status ~= 0 then
    monAtk = math.floor((monAtk * 150) / 100)
  end
  if abilityT == 63 and target.status ~= 0 then
    monDef = math.floor((monDef * 150) / 100)
  end
  if abilityA == 57 or abilityA == 58 then
    local partner = partnerOf(atk)
    local presence = battlerFacts(state, partner)
    if
      presence.hp --[[@as integer]]
      > 0
    then
      -- Each aura needs its living counterpart beside it: Plus reads
      -- Minus and Minus reads Plus. The partner read moves through the
      -- shared suppression model, so a suppressed partner carries no
      -- aura; the Mold Breaker arm cannot coincide with an aura holder
      -- here but keeps the read inside that model.
      local counterpart = 58
      if abilityA == 58 then
        counterpart = 57
      end
      local partnerAbility = presence.ability --[[@as integer]]
      if presence.suppressed == true then
        partnerAbility = 0
      end
      if partnerAbility == counterpart and not ignoredByMold(state) then
        monSpa = math.floor((monSpa * 150) / 100)
      end
    end
  end
  if moveType == 13 and facts.mudSport == true then
    movePower = math.floor(movePower / 2)
  end
  if moveType == 10 and facts.waterSport == true then
    movePower = math.floor(movePower / 2)
  end
  if abilityA == 65 and moveType == 12 and attacker.hp <= math.floor(attacker.maxHp / 3) then
    movePower = math.floor((movePower * 150) / 100)
  end
  if abilityA == 66 and moveType == 10 and attacker.hp <= math.floor(attacker.maxHp / 3) then
    movePower = math.floor((movePower * 150) / 100)
  end
  if abilityA == 67 and moveType == 11 and attacker.hp <= math.floor(attacker.maxHp / 3) then
    movePower = math.floor((movePower * 150) / 100)
  end
  if abilityA == 68 and moveType == 6 and attacker.hp <= math.floor(attacker.maxHp / 3) then
    movePower = math.floor((movePower * 150) / 100)
  end
  if abilityT == 85 and moveType == 10 then
    movePower = math.floor(movePower / 2)
  end
  if abilityT == 87 and moveType == 10 then
    movePower = math.floor((movePower * 125) / 100)
  end
  if abilityT == 47 and not ignoredByMold(state) and (moveType == 10 or moveType == 15) then
    movePower = math.floor(movePower / 2)
  end
  local function doubleStages(stages)
    local out = {}
    for index = 1, 8 do
      local delta = stages[index] --[[@as integer]] - 6
      delta = delta * 2
      if delta < -6 then
        delta = -6
      end
      if delta > 6 then
        delta = 6
      end
      out[index] = delta + 6
    end
    return out
  end
  local aStages = atkStages
  local dStages = defStages
  if abilityA == 86 then
    aStages = doubleStages(atkStages)
  end
  if abilityT == 86 and not ignoredByMold(state) then
    dStages = doubleStages(defStages)
  end
  local sAtk = 6
  local sDef = 6
  local sSpa = 6
  local sSpd = 6
  if abilityT == 109 and not ignoredByMold(state) then
    sAtk = 6
    sSpa = 6
  else
    sAtk = aStages[2]
    sSpa = aStages[5]
  end
  if abilityA == 109 then
    sDef = 6
    sSpd = 6
  else
    sDef = dStages[3]
    sSpd = dStages[6]
  end
  if abilityA == 79 then
    local genderA = attacker.gender
    local genderT = target.gender
    if genderA == nil or genderT == nil then
      error(BattleErrors.missingBehavior("trainer evaluation reads its battler gender", {}))
    end
    if genderA == genderT and genderA ~= 2 then
      movePower = math.floor((movePower * 125) / 100)
    elseif genderA ~= genderT and genderA ~= 2 and genderT ~= 2 then
      movePower = math.floor((movePower * 75) / 100)
    end
  end
  if abilityA == 89 and PUNCH_MOVES[moveId] == true then
    movePower = math.floor((movePower * 12) / 10)
  end
  local weatherClass = facts.weatherClass --[[@as integer]]
  if facts.airLock ~= true then
    if weatherClass == 2 and abilityA == 94 then
      monSpa = math.floor((monSpa * 15) / 10)
    end
    if weatherClass == 4 and (target.t1 == 5 or target.t2 == 5) then
      monSpd = math.floor((monSpd * 15) / 10)
    end
    if weatherClass == 3 then
      if abilityA == 122 then
        monAtk = math.floor((monAtk * 15) / 10)
      end
      if abilityT ~= 104 and facts.flowerGiftAtk == true then
        monAtk = math.floor((monAtk * 15) / 10)
      end
      if abilityA ~= 104 and facts.flowerGiftDef == true then
        monSpd = math.floor((monSpd * 15) / 10)
      end
    end
  end
  local byId = facts.moveById --[[@as table<integer, table<string, unknown>>]]
  local detail = byId[moveId]
  if type(detail) ~= "table" then
    error(BattleErrors.missingBehavior("trainer evaluation reads its compiled move facts", { move = moveId }))
  end
  local effect = detail.effect --[[@as integer]]
  local level = attacker.level --[[@as integer]]
  local damage = 0
  if category == 0 then
    local attack = stagedStat(monAtk, sAtk)
    damage = attack * movePower
    damage = damage * (math.floor((level * 2) / 5) + 2)
    damage = math.floor(damage / stagedStat(monDef, sDef))
    damage = math.floor(damage / 50)
    if attacker.status % 32 >= 16 and abilityA ~= 62 then
      damage = math.floor(damage / 2)
    end
    if facts.reflect == true and effect ~= 186 then
      damage = math.floor(damage / 2)
    end
  elseif category == 1 then
    local attack = stagedStat(monSpa, sSpa)
    damage = attack * movePower
    damage = damage * (math.floor((level * 2) / 5) + 2)
    damage = math.floor(damage / stagedStat(monSpd, sSpd))
    damage = math.floor(damage / 50)
    if facts.lightScreen == true and effect ~= 186 then
      damage = math.floor(damage / 2)
    end
  else
    error(BattleErrors.missingBehavior("trainer damage previews evaluate damaging moves", { move = moveId }))
  end
  return damage
end

-- Literal scale selection for the matchup previews (ov10_0221EF7C
-- core behind opcodes 32/99/105): the command operand selects the
-- stored slot threshold only for mode 1, and 100 otherwise.
---@param state TrainerAiProgramState command state under execution
---@param scaleMode integer literal scale operand under selection
---@param slot integer zero-based move slot under the preview
---@return integer 100 or the slot threshold under the final multiply
local function matchupScale(state, scaleMode, slot)
  if scaleMode == 1 then
    return state.thresholds[slot + 1]
  end
  return 100
end

-- Four-move staged preview for the battler named by the supplied facts:
-- every slot runs the matchup preview in source slot order against the
-- unchanged target using the literal scale rule above. No rank,
-- eligibility, or branch decision lives here.
---@param state TrainerAiProgramState command state under execution
---@param scaleMode integer literal scale operand under the previews
---@return integer[] staged matchup values for move slots 0..3 in order
local function matchupValues(state, scaleMode)
  local values = {}
  for slot = 0, 3 do
    values[slot + 1] = matchupValue(state, slot, matchupScale(state, scaleMode, slot))
  end
  return values
end

-- Current-move eligibility for the matchup ranks: moves outside the
-- evaluation class (excluded effects, power 0/1) never rank and leave
-- zero to their caller.
---@param state TrainerAiProgramState command state under execution
---@return boolean true while the current move enters the preview loop
local function matchupEligible(state)
  local facts = state.facts --[[@as table<string, unknown>]]
  local byId = facts.moveById --[[@as table<integer, table<string, unknown>>]]
  local record = byId[state.cur]
  if type(record) ~= "table" then
    error(BattleErrors.missingBehavior("trainer evaluation reads its compiled move facts", {
      move = state.cur,
    }))
  end
  local effect = record.effect --[[@as integer]]
  local power = record.power --[[@as integer]]
  if INCLUDED_EFFECTS[effect] ~= true then
    if EXCLUDED_EFFECTS[effect] == true or power <= 1 then
      return false
    end
  end
  return true
end

-- Effectiveness-class ranking into scratch (handler ov10_0221CD34 for
-- opcode 32): ineligible moves leave zero; otherwise every slot runs
-- the matchup preview under the literal scale operand and the current
-- slot leads-or-ties for 2, trails for 1.
---@param state TrainerAiProgramState command state under execution
---@param scaleMode integer literal scale operand under the previews
---@return integer effectiveness class 0/1/2 under the rank
function matchupRank(state, scaleMode)
  if not matchupEligible(state) then
    return 0
  end
  local ownValues = matchupValues(state, scaleMode)
  -- Rank demotion is strict. Ties keep the selected move at rank 2.
  local selected = ownValues[state.slot + 1]
  for _, value in ipairs(ownValues) do
    if value > selected then
      return 1
    end
  end
  return 2
end

