-- Version-scoped private cache in one of two explicit modes. `forVersion` is
-- the physical root: every path is normalized and confined below the version
-- prefix, and source bindings, saves-adjacent metadata, and explicit tooling
-- read and write it with the host backend. `fromStore` is the selected epoch's
-- resident generated reader: it answers from compact in-memory bytes and never
-- consults or writes a file. A version id is any safe path component, and which
-- ids exist is the ROM catalog's business, not this package's. Confinement,
-- backend handling, parent creation, and Lua loading share the internal
-- ScopedFs mechanics with SaveFs; the cache root, allowed mutations (tree
-- deletion, module loading), and CACHE_* error namespace stay its own. The
-- backend is injectable: the default wraps love.filesystem; tests inject an
-- in-memory fake. Path/security logic is love-free and testable under bare
-- LuaJIT.
--
-- Failure convention: every mutating operation reports success only if the
-- backend did; a falsy backend result is translated into a structured CACHE_*
-- error that reaches the caller, and a backend that raises propagates. No
-- mutating method may silently return true after a backend failure.

local Errors = require("libs.errors.src.Errors")
local LuaWriter = require("libs.codec.src.LuaWriter")
local ScopedFs = require("libs.storage.src.ScopedFs")
local StorageErrors = require("libs.storage.src.errors")

-- The CACHE_* codes this type raises through the shared mechanics.
local CACHE_ERRORS = {
  PATH_INVALID = StorageErrors.CACHE_PATH_INVALID,
  FILE_MISSING = StorageErrors.CACHE_FILE_MISSING,
  READ_FAILED = StorageErrors.CACHE_READ_FAILED,
  LUA_PARSE_FAILED = StorageErrors.CACHE_LUA_PARSE_FAILED,
  LUA_EVAL_FAILED = StorageErrors.CACHE_LUA_EVAL_FAILED,
  MKDIR_FAILED = StorageErrors.CACHE_MKDIR_FAILED,
  WRITE_FAILED = StorageErrors.CACHE_WRITE_FAILED,
  REMOVE_FAILED = StorageErrors.CACHE_REMOVE_FAILED,
  REPLACE_FAILED = StorageErrors.CACHE_REPLACE_FAILED,
}

---@class CacheFs.PackageRef
---@field sourceId string selected epoch plus the package supplying the entry
---@field contentId string the source id plus the logical path
---@field path string logical generated path
---@field size integer declared uncompressed member size
---@field physicalPath string confined mounted member path

-- The read shape a selected session's ordered package set exposes: winner
-- lookup from frozen metadata and one immediate read of that exact winner.
---@class CacheFs.PackageSet
---@field closed boolean? a retired set serves nothing instead of being consulted
---@field resolveAsset fun(self: CacheFs.PackageSet, path: string): CacheFs.PackageRef?
---@field paths fun(self: CacheFs.PackageSet, prefix: string): string[]
---@field readData fun(self: CacheFs.PackageSet, reference: CacheFs.PackageRef): love.Data

---@class CacheFs
---@field versionId string
---@field private _prefix string
---@field private _root string
---@field private _resident ResidentCache?
---@field private _base CacheFs?
---@field private _packages CacheFs.PackageSet?
---@field backend ScopedFs.Backend
---@field prefix fun(self: CacheFs): string
---@field resolve fun(self: CacheFs, relativePath: string): string
---@field write fun(self: CacheFs, relativePath: string, data: string|love.Data): boolean
---@field read fun(self: CacheFs, relativePath: string): string?
---@field getInfo fun(self: CacheFs, relativePath: string): table<string, unknown>?
---@field getDirectoryItems fun(self: CacheFs, relativePath: string): string[]
---@field exists fun(self: CacheFs, relativePath: string, expectedType?: string): boolean
---@field createDirectory fun(self: CacheFs, relativePath: string): boolean
---@field remove fun(self: CacheFs, relativePath: string): boolean
---@field replace fun(self: CacheFs, sourceRelativePath: string, destinationRelativePath: string): boolean
---@field replaceAt fun(self: CacheFs, sourcePath: string, destinationPath: string): boolean
---@field removeTree fun(self: CacheFs, relativePath: string): boolean
---@field writeLua fun(self: CacheFs, relativePath: string, value: table<string, unknown>): boolean
---@field loadLua fun(self: CacheFs, relativePath: string): table<string, unknown>?, Errors.Error?
local CacheFs = {}
CacheFs.__index = CacheFs

---@param versionId string
---@param backend table<string, unknown>|nil
---@return CacheFs
function CacheFs.forVersion(versionId, backend)
  ScopedFs.validateVersionId(versionId)
  return setmetatable({
    versionId = versionId,
    _prefix = versionId .. "/",
    _root = versionId,
    backend = backend or ScopedFs.loveBackend(),
  }, CacheFs)
end

function CacheFs:prefix()
  return self._prefix
end

-- A reader over the selected epoch's resident generated bytes. The bytes are
-- authoritative in memory, so this view performs no physical lookup and has no
-- disk fallback: a path the store does not hold is simply absent. Runtime
-- consumers resolve BlobRefs from it; the string/Lua accessors exist for the
-- small metadata readers that still consume logical bytes as text.
---@param store ResidentCache
---@return CacheFs
function CacheFs.fromStore(store)
  assert(type(store) == "table" and type(store.versionId) == "string", "resident reader requires its byte store")
  return setmetatable({
    versionId = store.versionId,
    _prefix = store.versionId .. "/",
    _root = store.versionId,
    _resident = store,
  }, CacheFs)
end

---@return boolean
function CacheFs:isResident()
  if self._packages ~= nil then
    return self:_baseReader():isResident()
  end
  return self._resident ~= nil
end

-- The read-only view a selected session composes before any generated consumer
-- exists: the same version and base owner, plus the ordered package set whose
-- winners are resolved before the base reader answers. The overlay copies no
-- bytes and owns no mount, so retiring it never closes either layer.
---@param packageSet CacheFs.PackageSet
---@return CacheFs
function CacheFs:withPackages(packageSet)
  assert(self._base == nil, "a selected overlay is not overlaid again")
  assert(type(packageSet) == "table", "a selected overlay needs its ordered package set")
  return setmetatable({
    versionId = self.versionId,
    _prefix = self._prefix,
    _root = self._root,
    _base = self,
    _packages = packageSet,
  }, CacheFs)
end

-- The base owner this overlay delegates to; an overlay always has one.
---@return CacheFs
function CacheFs:_baseReader()
  return assert(self._base, "a selected package overlay requires its base reader")
end

-- The selected winner for one logical path, or nil when the package layer is
-- absent or already retired. The caller decides whether an unselected path
-- falls through to the base reader.
---@param path string
---@return CacheFs.PackageRef? reference
---@return CacheFs.PackageSet? packageSet
function CacheFs:_selectedWinner(path)
  local packages = self._packages
  if packages == nil or packages.closed == true then
    return nil, packages
  end
  return packages:resolveAsset(path), packages
end

-- A directory the base never carried still exists in the selection when a
-- winner lives below it, so existence, info, and enumeration agree.
---@param path string
---@return boolean
function CacheFs:_hasSelectedChild(path)
  local packages = self._packages
  if packages == nil or packages.closed == true then
    return false
  end
  return #packages:paths(path == "" and "" or path .. "/") > 0
end

-- Neither resident bytes nor a selected package overlay can be written: an
-- overlay borrows both layers and owns nothing it may mutate.
---@return boolean
function CacheFs:_rejectsMutation()
  if self._packages ~= nil then
    error("a selected package overlay is immutable", 2)
  end
  assert(self._resident == nil, "resident generated bytes are immutable")
  return true
end

-- Resident Lua chunks are evaluated from their own bytes through the shared
-- confined loader: the same parse/eval error codes, no physical backend.
---@return ScopedFs.Backend
function CacheFs:_residentBackend()
  local store = assert(self._resident, "resident backend requires a resident store")
  local function residentGetInfo(_, path)
    return store:getInfo(path)
  end
  local function residentRead(_, path)
    local data = store:readData(path)
    if data == nil then
      return nil, "no such resident entry"
    end
    return data:getString()
  end
  return { getInfo = residentGetInfo, read = residentRead }
end

-- Normalize and confine a relative path, returning the full save-dir path.
-- Raises a structured error on any escape attempt. "" means the version root.
-- A selected overlay and a resident reader are logical views only: `resolve`
-- stays a diagnostic key and never becomes a host path.
function CacheFs:resolve(relativePath)
  assert(self._packages == nil, "a selected package overlay is not a host path")
  assert(self._resident == nil, "a resident generated reader is not a host path")
  return ScopedFs.resolve(self._root, relativePath, CACHE_ERRORS)
end

---@param path string
---@return ResidentCache.BlobRef|CacheFs.PackageRef|nil
function CacheFs:resolveAsset(path)
  if self._packages ~= nil then
    local winner = self:_selectedWinner(path)
    if winner ~= nil then
      return winner
    end
    return self:_baseReader():resolveAsset(path)
  end
  local store = self._resident
  if store == nil then
    return nil
  end
  return store:resolveAsset(path)
end

---@param path string
---@return love.Data|nil
function CacheFs:readData(path)
  if self._packages ~= nil then
    local winner, packages = self:_selectedWinner(path)
    if winner ~= nil then
      return assert(packages, "a selected winner belongs to its package set"):readData(winner)
    end
    return self:_baseReader():readData(path)
  end
  local store = self._resident
  if store == nil then
    return nil
  end
  return store:readData(path)
end

function CacheFs:write(relativePath, data)
  self:_rejectsMutation()
  return ScopedFs.write(self.backend, self:resolve(relativePath), data, CACHE_ERRORS)
end

function CacheFs:read(relativePath)
  if self._packages ~= nil then
    local winner, packages = self:_selectedWinner(relativePath)
    if winner ~= nil then
      return assert(packages, "a selected winner belongs to its package set"):readData(winner):getString()
    end
    return self:_baseReader():read(relativePath)
  end
  if self._resident ~= nil then
    local data = self._resident:readData(relativePath)
    if data == nil then
      return nil
    end
    return data:getString()
  end
  return self.backend:read(self:resolve(relativePath))
end

function CacheFs:getInfo(relativePath)
  if self._packages ~= nil then
    local winner = self:_selectedWinner(relativePath)
    if winner ~= nil then
      return { path = winner.path, type = "file", size = winner.size }
    end
    if self:_hasSelectedChild(relativePath) then
      return { path = relativePath, type = "directory", size = 0 }
    end
    return self:_baseReader():getInfo(relativePath)
  end
  if self._resident ~= nil then
    return self._resident:getInfo(relativePath)
  end
  return self.backend:getInfo(self:resolve(relativePath))
end

-- Lists one directory and raises when the backend cannot answer. Cleanup code
-- must distinguish an empty directory from a failed listing. A selected overlay
-- unions each layer's direct children once, sorted, from metadata alone.
function CacheFs:getDirectoryItems(relativePath)
  if self._packages ~= nil then
    local names = {}
    for _, name in ipairs(self:_baseReader():getDirectoryItems(relativePath)) do
      names[name] = true
    end
    local packages = self._packages
    if packages ~= nil and packages.closed ~= true then
      local prefix = relativePath == "" and "" or relativePath .. "/"
      for _, path in ipairs(packages:paths(prefix)) do
        local name = path:sub(#prefix + 1):match("^([^/]+)")
        if name ~= nil then
          names[name] = true
        end
      end
    end
    local items = {}
    for name in pairs(names) do
      items[#items + 1] = name
    end
    table.sort(items)
    return items
  end
  if self._resident ~= nil then
    return self._resident:getDirectoryItems(relativePath)
  end
  local full = self:resolve(relativePath)
  local items, err = self.backend:getDirectoryItems(full)
  if items == nil then
    Errors.raise(CACHE_ERRORS.READ_FAILED, err or "could not list directory", { path = full })
  end
  ---@cast items -nil
  return items
end

function CacheFs:exists(relativePath, expectedType)
  if self._packages ~= nil then
    if self:_selectedWinner(relativePath) ~= nil then
      return expectedType == nil or expectedType == "file"
    end
    if self:_hasSelectedChild(relativePath) and (expectedType == nil or expectedType == "directory") then
      return true
    end
    return self:_baseReader():exists(relativePath, expectedType)
  end
  if self._resident ~= nil then
    return self._resident:exists(relativePath, expectedType)
  end
  local info = self.backend:getInfo(self:resolve(relativePath))
  if not info then
    return false
  end
  if expectedType then
    return info.type == expectedType
  end
  return true
end

function CacheFs:createDirectory(relativePath)
  self:_rejectsMutation()
  local full = self:resolve(relativePath)
  local ok, err = self.backend:createDirectory(full)
  return ScopedFs.ensureBackend(ok, err, CACHE_ERRORS.MKDIR_FAILED, "could not create directory", { path = full })
end

-- Removing an absent path is a no-op; removing an existing path that the
-- backend cannot remove raises CACHE_REMOVE_FAILED.
function CacheFs:remove(relativePath)
  self:_rejectsMutation()
  return ScopedFs.remove(self.backend, self:resolve(relativePath), CACHE_ERRORS)
end

-- Atomically replaces destination with an already-written sibling file. The
-- default backend uses the host rename primitive inside LÖVE's save directory.
function CacheFs:replace(sourceRelativePath, destinationRelativePath)
  self:_rejectsMutation()
  local source = self:resolve(sourceRelativePath)
  local destination = self:resolve(destinationRelativePath)
  return self:replaceAt(source, destination)
end

-- Backend rename at save-directory-absolute paths with the standard failure
-- convention (CACHE_REPLACE_FAILED on a falsy backend result), so a backend
-- that reports failure can never make a caller report success.
function CacheFs:replaceAt(sourcePath, destinationPath)
  self:_rejectsMutation()
  return ScopedFs.replace(self.backend, sourcePath, destinationPath, CACHE_ERRORS)
end

function CacheFs:removeTree(relativePath)
  self:_rejectsMutation()
  self:_removeTreeAt(self:resolve(relativePath))
  return true
end

-- Recursively remove a save-directory-absolute path; a no-op when absent.
-- Any backend-reported removal or enumeration failure raises
-- CACHE_REMOVE_FAILED instead of silently reporting success.
function CacheFs:_removeTreeAt(fullPath)
  local function rec(path)
    local info = self.backend:getInfo(path)
    if not info then
      return
    end
    if info.type == "directory" then
      local items = self.backend:getDirectoryItems(path)
      if not items then
        Errors.raise(CACHE_ERRORS.REMOVE_FAILED, "could not list directory", { path = path })
      end
      for _, name in ipairs(items) do
        rec(path .. "/" .. name)
      end
    end
    local ok, err = self.backend:remove(path)
    ScopedFs.ensureBackend(ok, err, CACHE_ERRORS.REMOVE_FAILED, "could not remove", { path = path })
  end
  rec(fullPath)
end

function CacheFs:writeLua(relativePath, value)
  return self:write(relativePath, LuaWriter.encode(value))
end

-- Evaluate one selected package member through the shared confined loader: the
-- winner's own bytes are the chunk source and the empty/allowlisted environment
-- policy stays the loader's. A path the selection does not name keeps the base
-- reader's own load behavior.
---@param relativePath string
---@param env table<string, function>?
---@return table<string, unknown>?, Errors.Error?
function CacheFs:_loadSelectedChunk(relativePath, env)
  local winner, packages = self:_selectedWinner(relativePath)
  if winner == nil then
    if env == nil then
      return self:_baseReader():loadLua(relativePath)
    end
    return self:_baseReader():loadModule(relativePath)
  end
  local set = assert(packages, "a selected winner belongs to its package set")
  local reference = winner --[[@as CacheFs.PackageRef]]
  local function selectedGetInfo()
    return { type = "file", size = reference.size }
  end
  local function selectedRead()
    return set:readData(reference):getString()
  end
  local backend = { getInfo = selectedGetInfo, read = selectedRead }
  local ok, result, loadErr = pcall(ScopedFs.loadChunk, backend, relativePath, relativePath, CACHE_ERRORS, env)
  if ok then
    return result, loadErr
  end
  if Errors.is(result) then
    return nil, result
  end
  error(result, 0)
end

-- Loads a generated/checked-in Lua data file in an empty environment. Must
-- never be pointed at raw ROM file contents.
function CacheFs:loadLua(relativePath)
  if self._packages ~= nil then
    return self:_loadSelectedChunk(relativePath, nil)
  end
  local fullPath = relativePath
  local backend = self.backend
  if self._resident ~= nil then
    backend = self:_residentBackend()
  else
    fullPath = self:resolve(relativePath)
  end
  local ok, result, loadErr = pcall(ScopedFs.loadChunk, backend, fullPath, relativePath, CACHE_ERRORS)
  if ok then
    return result, loadErr
  end
  if Errors.is(result) then
    return nil, result
  end
  error(result, 0)
end

-- The one module a generated chunk may require: the gen4 script DSL emitted
-- by the script cache generator. Mirrors ScriptLoader's resource-loader
-- allowlist; anything wider would let generated cache content reach (and
-- corrupt) process-wide package state.
local ALLOWED_MODULES = { ["gen4.script"] = true }

local function moduleRequire(name)
  assert(ALLOWED_MODULES[name], "generated modules may only require gen4.script")
  return require(name)
end

-- Loads a generated Lua module (a file that `require`s other modules) in an
-- environment whose only entry is a require restricted to the gen4.script
-- allowlist. Used by the script-cache readback and by runtime loaders that
-- consume generated DSL modules. Must never be pointed at raw ROM file
-- contents. A module requiring outside the allowlist fails to load.
function CacheFs:loadModule(relativePath)
  if self._packages ~= nil then
    return self:_loadSelectedChunk(relativePath, { require = moduleRequire })
  end
  local fullPath = relativePath
  local backend = self.backend
  if self._resident ~= nil then
    backend = self:_residentBackend()
  else
    fullPath = self:resolve(relativePath)
  end
  local ok, result, loadErr = pcall(ScopedFs.loadChunk, backend, fullPath, relativePath, CACHE_ERRORS, {
    require = moduleRequire,
  })
  if ok then
    return result, loadErr
  end
  if Errors.is(result) then
    return nil, result
  end
  error(result, 0)
end

return CacheFs
