-- Owns producer worker threads, priority scheduling, and serialized memory
-- publication. A process-owned pool admits canonical jobs for one selected
-- game version and generation epoch at a time. Each job carries its explicit
-- version, generation, epoch, kind, key, priority, size class, and declared
-- dependency closure. A worker returns immutable output entries; this pool is
-- the single publisher that reconciles shared content, commits bytes and the
-- artifact fact together, and is the only owner of the selected byte store.
-- Physical worker occupancy is tracked separately from queued interest so
-- retiring a game epoch never frees a still-executing worker.

