-- Start the selected generation from an earlier captured cut: the hydrated
-- bytes and facts of a snapshot this process opened become this selection's
-- content, so the graph reuses them and compiles only genuine misses. The
-- caller has already validated the cut against the selected generation; entry
-- identities are minted here, by the one publisher, exactly as a fresh commit
-- mints them. Seeding is not a publication of this process.
---@param entries { path: string, data: love.Data, size: integer }[]
---@param artifacts ArtifactState.Fact[]
function CompilerPool:seedCommittedGeneration(entries, artifacts)
  assert(not self.closed, "compiler pool is shut down")
  local store = assert(self.store, "compiler pool has no committed store")
  local facts = assert(self.facts, "compiler pool has no committed facts")
  assert(type(entries) == "table" and type(artifacts) == "table", "a seeded cut carries entries and artifacts")
  local wanted = {}
  for index, entry in ipairs(entries) do
    assert(type(entry) == "table" and type(entry.path) == "string", "a seeded entry carries its logical path")
    wanted[index] = {
      path = entry.path,
      data = entry.data,
      size = entry.data:getSize(),
      sourceId = store:sourceId(),
      contentId = facts.generationId .. "\0" .. entry.path,
    }
  end
  store:commit(store:prepare(wanted))
  for _, artifact in ipairs(artifacts) do
    ArtifactState.commitFact(facts, artifact)
  end
end

-- One consistent cut of the selected generation: the committed bytes and facts
-- plus the completion facts the caller owns. Entries are shallow references to
-- the immutable committed Data, so a capture of the whole corpus copies no
-- payload and cannot observe a later commit.
---@param identity table<string, unknown> the selected generation identity
---@param completion { sequence: integer, milestones: string[]?, firstPlay: boolean?, complete: boolean? }
---@return table<string, unknown> cut
function CompilerPool:snapshotCut(identity, completion)
  assert(type(identity) == "table" and type(completion) == "table", "a snapshot cut carries identity and facts")
  local selected = assert(self.selected, "compiler pool has no selected generation")
  assert(selected.versionId == identity.versionId, "a snapshot cut names the selected version")
  assert(selected.generationId == identity.generationId, "a snapshot cut names the selected generation")
  local store = assert(self.store, "compiler pool has no committed store")
  local facts = assert(self.facts, "compiler pool has no committed facts")
  local entries = {}
  local seen = {}
  local artifacts = {}
  for _, fact in pairs(facts.records) do
    artifacts[#artifacts + 1] = fact
    for _, path in ipairs(fact.files) do
      if not seen[path] then
        seen[path] = true
        local reference = assert(store:resolveAsset(path), "committed fact file is missing from the store: " .. path)
        entries[#entries + 1] = reference
      end
    end
  end
  return {
    versionId = selected.versionId,
    identity = identity,
    sequence = completion.sequence,
    entries = entries,
    artifacts = artifacts,
    milestones = completion.milestones or {},
    firstPlay = completion.firstPlay == true,
    complete = completion.complete == true,
  }
end

---@param identity table<string, unknown>
---@param epoch integer
function CompilerPool:_replaceCommittedGeneration(identity, epoch)
  self:_closeCommittedGeneration()
  local generationId = assert(identity.generationId, "compiler pool generationId is required")
  local store =
    ResidentCache.new(assert(identity.versionId, "compiler pool versionId is required"), "base:" .. generationId)
  self.store = store
  self.storeReader = CacheFs.fromStore(store)
  self.facts = ArtifactState.new(generationId)
  self.publishedCommits = 0
  self.committedEpoch = epoch
end

function CompilerPool:_closeCommittedGeneration()
  if self.store ~= nil then
    self.store:close()
  end
  self.store = nil
  self.storeReader = nil
  self.facts = nil
  self.committedEpoch = nil
end

-- One job's closed dependency view: the transitive closure of its declared
-- prerequisites, resolved to their committed facts and to the immutable
-- entries those facts own. Everything the worker may read travels here.
---@param record CompilerPool.Job
---@return { sourceId: string, artifacts: ArtifactState, entries: ResidentCache.BlobRef[] }
function CompilerPool:_dependencyView(record)
  local store = assert(self.store, "compiler pool has no committed store")
  local facts = assert(self.facts, "compiler pool has no committed facts")
  local queue = {}
  for _, dependency in ipairs(record.dependencies) do
    queue[#queue + 1] = dependency.kind .. ":" .. dependency.key
  end
  local ordered = {}
  local source = {}
  local index = 1
  while index <= #queue do
    local identity = queue[index]
    index = index + 1
    if source[identity] == nil then
      local fact = facts.records[identity]
      assert(fact ~= nil, "declared dependency is not committed for this generation: " .. identity)
      source[identity] = fact
      ordered[#ordered + 1] = identity
      for _, child in ipairs(fact.dependencies) do
        queue[#queue + 1] = child
      end
    end
  end
  table.sort(ordered)
  local entries = {}
  local seen = {}
  for _, identity in ipairs(ordered) do
    for _, path in ipairs(source[identity].files) do
      if not seen[path] then
        seen[path] = true
        local reference = store:resolveAsset(path)
        assert(reference ~= nil, "committed fact file is missing from the store: " .. path)
        entries[#entries + 1] = reference
      end
    end
  end
  return {
    sourceId = store:sourceId(),
    artifacts = { generationId = facts.generationId, records = source },
    entries = entries,
  }
end

function CompilerPool:selectGeneration(identity, epoch)
  assert(not self.closed, "compiler pool is shut down")
  assert(type(identity) == "table", "compiler pool generation identity is required")
  assert(type(identity.versionId) == "string" and identity.versionId ~= "", "compiler pool versionId is required")
  assert(
    type(identity.generationId) == "string" and identity.generationId ~= "",
    "compiler pool generationId is required"
  )
  assert(type(epoch) == "number" and epoch % 1 == 0 and epoch >= 1, "compiler pool epoch must be a positive integer")
  local current = self.selected
  if
    current
    and current.versionId == identity.versionId
    and current.generationId == identity.generationId
    and current.epoch == epoch
  then
    return
  end
  if self.quiescing and not self:isQuiescent() then
    error("compiler pool quiescence barrier is incomplete", 0)
  end
  for _, record in pairs(self.jobs) do
    if record.state == "queued" then
      record.state = "cancelled"
      record.node = nil
    end
  end
  resetLanes(self)
  for _, completion in ipairs(self.completions) do
    if self.jobs[completion.record.jobKey] == completion.record then
      completion.record.state = "cancelled"
    end
    -- A prepared result pins its worker until publication drains it.
    -- Dropping the completion queue must release that pin: the worker
    -- would otherwise stay busy forever behind a cancelled record.
    self:_freeSlot(completion.record, completion.workerId)
  end
  self.completions = {}
  -- Running slots stay physically busy under their old identity but leave the
  -- selected lookup, so an equal kind:key requested for the new epoch is new
  -- interest rather than a promotion of the retired record.
  self.jobs = {}
  self:_replaceCommittedGeneration(identity, epoch)
  -- A new selection never inherits the old buffer, its borrowers, or its
  -- waiters: suspended old-epoch workers are released with a typed cause.
  self:_failSourceWaiters(
    sourceErrorTable(Errors.new("SOURCE_EPOCH_RETIRED", "the compiler pool reselected while source was awaited", {}))
  )
  self:_dropSharedSource()
  self.sourceReleaseWait = {}
  self.sourceReleaseOpen = false
  self.bootSourceHold = nil
  self.sourceSettledQuery = nil
  self.selected = { versionId = identity.versionId, generationId = identity.generationId, epoch = epoch }
  -- The physical reader stays for source binding/import metadata only; no
  -- generated asset is ever read or written through it.
  self.selectedCacheFs = CacheFs.forVersion(identity.versionId)
  self.quiescing = false
  self.retired = false
  for _, worker in ipairs(self.workers) do
    worker.closeSent = false
    worker.closeAcked = false
    worker.closeAfter = false
    worker.closeToken = nil
    worker.srcCloseToken = nil
  end
  -- A completed barrier may have joined exiting workers without restarting
  -- them; recreate that capacity for the new owner.
  for _, worker in ipairs(self.workers) do
    if worker.joined then
      local ok, replacement = pcall(startWorker, self.resultChannel, worker.id, self.developmentRepositoryRoot)
      if not ok then
        self.fatalError = restoreError(replacement)
        error(replacement, 0)
      end
      self.workers[worker.id] = replacement
    end
  end
end

---@param epoch integer
---@return boolean
function CompilerPool:retireSelection(epoch)
  assert(not self.closed, "compiler pool is shut down")
  local selected = self.selected
  if selected == nil or self.retired then
    return false
  end
  assert(type(epoch) == "number" and epoch % 1 == 0, "compiler pool epoch must be an integer")
  if epoch ~= selected.epoch then
    return false
  end
  -- Suspended source waiters belong to the retired epoch: release them
  -- with a typed cause so no worker waits forever, then forget the buffer.
  -- Running borrowers keep their own borrowed views until the existing
  -- close barriers prove closure.
  self:_failSourceWaiters(
    sourceErrorTable(
      Errors.new("SOURCE_EPOCH_RETIRED", "the selected generation was retired while source was awaited", {})
    )
  )
  self:_dropSharedSource()
  self.sourceReleaseWait = {}
  self.sourceReleaseOpen = false
  self.bootSourceHold = nil
  for _, worker in ipairs(self.workers) do
    worker.srcCloseToken = nil
  end
  -- Logical interest is cancelled; executing physical slots stay charged
  -- under their old identity until their terminal reply or joined exit.
  self.retired = true
  for _, record in pairs(self.jobs) do
    if record.state == "queued" then
      record.state = "cancelled"
      record.node = nil
    end
  end
  resetLanes(self)
  for _, completion in ipairs(self.completions) do
    if self.jobs[completion.record.jobKey] == completion.record then
      completion.record.state = "cancelled"
    end
    self:_freeSlot(completion.record, completion.workerId)
  end
  self.completions = {}
  -- A retired selection grants no new generated lookups; bytes already
  -- borrowed stay alive through their holders.
  self:_closeCommittedGeneration()
  return true
end

local function assertJobShape(job, selected)
  assert(type(job) == "table", "compiler job must be a table")
  assert(type(job.versionId) == "string" and job.versionId ~= "", "compiler job versionId is required")
  assert(type(job.generationId) == "string" and job.generationId ~= "", "compiler job generationId is required")
  assert(type(job.epoch) == "number" and job.epoch % 1 == 0, "compiler job epoch must be an integer")
  assert(ArtifactState.KINDS[job.kind], "unsupported compiler job kind: " .. tostring(job.kind))
  assert(type(job.key) == "string" and job.key ~= "", "compiler job key is required")
  ArtifactState.validateKey(job.kind, job.key)
  assert(type(job.jobKey) == "string" and job.jobKey ~= "", "compiler job jobKey is required")
  assert(job.jobKey == job.kind .. ":" .. job.key, "compiler job identity must match its kind and key")
  assert(
    type(job.priority) == "number" and job.priority % 1 == 0 and FIXED_PRIORITIES[job.priority],
    "compiler job priority must be 0, 10, or 100"
  )
  assert(SIZE_CLASSES[job.sizeClass], "compiler job sizeClass must be normal, heavy, or jumbo")
  assert(type(job.payload) == "table", "compiler job payload is required")
  assert(type(job.dependencies) == "table", "compiler job dependencies are required")
  local seenDependency = {}
  for _, dependency in ipairs(job.dependencies) do
    assert(type(dependency) == "table", "compiler job dependency must be a job selector")
    local identity = ArtifactState.key(dependency.kind, dependency.key)
    assert(not seenDependency[identity], "compiler job dependency is listed twice: " .. identity)
    seenDependency[identity] = true
  end
  if selected then
    assert(job.versionId == selected.versionId, "compiler job version does not match the selected generation")
    assert(job.generationId == selected.generationId, "compiler job generation does not match the selected generation")
    assert(job.epoch == selected.epoch, "compiler job epoch does not match the selected generation")
  end
  if job.kind == "map" then
    assert(type(job.payload.mapId) == "number" and job.payload.mapId % 1 == 0, "map job requires an integer mapId")
  elseif job.kind == "field-cell" then
    for _, key in ipairs({
      "matrixMemberId",
      "index",
      "x",
      "z",
      "mapHeaderId",
      "altitude",
      "landDataMemberId",
      "areaDataMemberId",
    }) do
      assert(type(job.payload[key]) == "number" and job.payload[key] % 1 == 0, "field-cell job requires " .. key)
    end
  elseif job.kind == "script-member" then
    assert(
      type(job.payload.memberId) == "number" and job.payload.memberId % 1 == 0,
      "script member job requires an integer memberId"
    )
    assert(
      type(job.payload.generationKey) == "string" and job.payload.generationKey ~= "",
      "script member generation is required"
    )
  end
end

function CompilerPool:request(job)
  assert(not self.closed, "compiler pool is shut down")
  if self.fatalError then
    error(self.fatalError, 0)
  end
  assert(not self.quiescing, "compiler pool is quiescing")
  assert(not self.retired, "compiler pool selection is retired")
  local selected = assert(self.selected, "compiler pool has no selected generation")
  assertJobShape(job, selected)
  local existing = self.jobs[job.jobKey]
  if existing then
    if existing.state == "failed" then
      error(existing.details and existing.details.error or "compiler job failed", 2)
    end
    if existing.state == "cancelled" then
      self.jobs[job.jobKey] = nil
    else
      if existing.state == "queued" and job.priority < existing.priority then
        -- Promotion keeps the original FIFO sequence: the old lane node
        -- goes stale because the record no longer points at it, and the
        -- new node carries the same sequence into the stronger lane.
        existing.priority = job.priority
        existing.node = {
          key = existing.jobKey,
          priority = job.priority,
          sizeClass = existing.sizeClass,
          sequence = existing.sequence,
        }
        insertOrderedLane(self.lanes, existing.node)
      end
      return existing.state, existing.details
    end
  end

  -- A generation that already proves this artifact owns its bytes and
  -- dependency facts: a hydrated cut or an earlier commit settles the request
  -- without occupying a worker or publishing the same output twice.
  local committed = ArtifactState.read(self.facts, job.kind, job.key)
  if committed ~= nil then
    self.sequence = self.sequence + 1
    local reused = {
      versionId = job.versionId,
      generationId = job.generationId,
      epoch = job.epoch,
      key = job.key,
      kind = job.kind,
      jobKey = job.jobKey,
      dependencies = job.dependencies,
      payload = job.payload,
      priority = job.priority,
      sizeClass = job.sizeClass,
      sequence = self.sequence,
      state = "ready",
      node = nil,
      details = { result = { marker = committed.marker } },
    }
    self.jobs[job.jobKey] = reused
    return reused.state, reused.details
  end

  self.sequence = self.sequence + 1
  local record = {
    versionId = job.versionId,
    generationId = job.generationId,
    epoch = job.epoch,
    key = job.key,
    kind = job.kind,
    jobKey = job.jobKey,
    dependencies = job.dependencies,
    payload = job.payload,
    priority = job.priority,
    sizeClass = job.sizeClass,
    sequence = self.sequence,
    state = "queued",
    node = nil,
    details = nil,
  }
  record.node = {
    key = record.jobKey,
    priority = record.priority,
    sizeClass = record.sizeClass,
    sequence = record.sequence,
  }
  self.jobs[record.jobKey] = record
  enqueueLane(self.lanes, record.node)
  self.queuedCount = self.queuedCount + 1
  return record.state
end

function CompilerPool:retry(jobKey, priority)
  assert(not self.closed, "compiler pool is shut down")
  if self.fatalError then
    error(self.fatalError, 0)
  end
  assert(not self.quiescing, "compiler pool is quiescing")
  assert(not self.retired, "compiler pool selection is retired")
  local record = assert(self.jobs[jobKey], "unknown compiler job: " .. tostring(jobKey))
  assert(record.state == "failed", "only failed compiler jobs can be retried")
  assert(
    type(priority) == "number" and priority % 1 == 0 and FIXED_PRIORITIES[priority],
    "retry priority must be 0, 10, or 100"
  )
  self.sequence = self.sequence + 1
  record.priority = priority
  record.sequence = self.sequence
  record.details = nil
  record.state = "queued"
  -- A retry rejoins behind older same-priority work with a fresh sequence.
  record.node = {
    key = record.jobKey,
    priority = priority,
    sizeClass = record.sizeClass,
    sequence = self.sequence,
  }
  enqueueLane(self.lanes, record.node)
  self.queuedCount = self.queuedCount + 1
  return record.state
end

---@param jobKey string
---@return string
---@return table<string, unknown>?
function CompilerPool:status(jobKey)
  local record = self.jobs[jobKey]
  if not record then
    return "unknown"
  end
  if record.state == "queued" then
    local reason = self:_admissionBlockReason()
    if reason then
      return record.state, { waitingOn = reason }
    end
  end
  return record.state, record.details
end

---@param jobKey string
---@return table<string, unknown>|nil
function CompilerPool:jobOutcome(jobKey)
  local record = self.jobs[jobKey]
  if record == nil then
    return nil
  end
  local workerId = record.workerId
  if workerId == nil and type(record.details) == "table" then
    local detailWorker = record.details.workerId
    if type(detailWorker) == "number" then
      workerId = detailWorker
    end
  end
  local snapshot = {
    jobKey = record.jobKey,
    generationId = record.generationId,
    epoch = record.epoch,
    state = record.state,
  }
  if workerId ~= nil then
    snapshot.workerId = workerId
  end
  if record.state == "failed" and type(record.details) == "table" and record.details.error ~= nil then
    snapshot.error = record.details.error
  end
  if type(record.timing) == "table" then
    snapshot.compileSeconds = record.timing.compileSeconds
    snapshot.stageSeconds = record.timing.stageSeconds
    snapshot.workSeconds = record.timing.workSeconds
    snapshot.stagedBytes = record.timing.stagedBytes
    snapshot.timingReason = record.timing.timingReason
  end
  return snapshot
end

--- The one physical admission rule: a queued job waits only while every
--- worker is physically occupied (running or settling its one prepared
--- result) or the pool is draining. Family labels never serialize work.
---@return string?
function CompilerPool:_admissionBlockReason()
  if self.fatalError then
    return "infrastructure-failure"
  end
  if self.quiescing then
    return "quiescing"
  end
  if self:_runningCount() + #self.completions > #self.workers then
    return "prepared-backpressure"
  end
  for _, worker in ipairs(self.workers) do
    if workerIdle(worker) then
      return nil
    end
  end
  return "active-job"
end

---@return integer
function CompilerPool:_runningCount()
  local running = 0
  for _, worker in ipairs(self.workers) do
    if worker.slot ~= nil then
      running = running + 1
    end
  end
  return running
end

---@param versionId string
---@return CacheFs
function CompilerPool:_cacheFsFor(versionId)
  if self.selected and self.selectedCacheFs and versionId == self.selected.versionId then
    return self.selectedCacheFs
  end
  return CacheFs.forVersion(versionId)
end

-- Accept one verified ephemeral buffer for the live selection. The
-- controller validated the offer against its epoch and version identity;
-- the pool stores it only when it matches the current selection and no
-- buffer is held yet, and consumes it before any filesystem acquisition.
-- Stale or foreign offers are refused without effect.
---@param epoch integer
---@param byteData userdata
---@param descriptor table<string, unknown> { versionId, romSha1 }
---@return boolean accepted
function CompilerPool:offerSource(epoch, byteData, descriptor)
  local selected = self.selected
  if selected == nil or self.closed or type(epoch) ~= "number" or epoch ~= selected.epoch then
    return false
  end
  if type(descriptor) ~= "table" or descriptor.versionId ~= selected.versionId then
    return false
  end
  if type(byteData) ~= "userdata" then
    return false
  end
  local GameVersion = require("romdump.src.source.GameVersion")
  local info = GameVersion.VERSIONS[descriptor.versionId]
  if type(info) ~= "table" or info.sha1 ~= descriptor.romSha1 then
    return false
  end
  if self.sharedSource ~= nil then
    return true
  end
  self.offeredSource = {
    byteData = byteData,
    versionId = descriptor.versionId,
    romSha1 = descriptor.romSha1,
    epoch = epoch,
  }
  return true
end

-- Boot preflight: verify and pin the one immutable selected buffer before
-- the app is admitted, then hold it across the idle pre-sweep gap even
-- with zero worker borrowers. With needsSource=false the cache already
-- proved itself, so a queued offer is discarded with no file IO. With
-- needsSource=true a verified offer is consumed first, otherwise the exact
-- registered source (including its bound archive member) is opened once
-- and pinned. Idempotent for the live epoch: a held buffer is never
-- duplicated. Returns true, or nil plus a plain typed error; a failure
-- stores nothing and leaves prior receipts untouched.
---@param epoch integer
---@param needsSource boolean
---@return boolean? held
---@return table<string, unknown>? failure
function CompilerPool:prepareBootSource(epoch, needsSource)
  local selected = self.selected
  if self.closed or selected == nil or self.retired or self.quiescing then
    return nil,
      sourceErrorTable(Errors.new("SOURCE_EPOCH_RETIRED", "the compiler pool has no live selection to preflight", {}))
  end
  if type(epoch) ~= "number" or epoch ~= selected.epoch then
    return nil,
      sourceErrorTable(Errors.new("SOURCE_EPOCH_RETIRED", "boot preflight does not match the live selection", {}))
  end
  if needsSource ~= true then
    self.offeredSource = nil
    return true
  end
  local held = self.sharedSource
  if held ~= nil and held.epoch == selected.epoch then
    self.bootSourceHold = true
    return true
  end
  local byteData, acqErr = self:_acquireSharedSource(selected.versionId)
  if byteData == nil then
    assert(acqErr, "a failed acquisition names its cause")
    return nil, acqErr
  end
  self.sharedSource = {
    byteData = byteData,
    versionId = selected.versionId,
    generationId = selected.generationId,
    epoch = selected.epoch,
  }
  self.bootSourceHold = true
  return true
end

-- Release the deliberate pre-sweep retention after the full-generation
-- attestation is durable, delegating actual borrower closure to the
-- existing release protocol. A stale epoch is refused without effect;
-- quiescence and retirement clear the hold through their own barriers.
---@param epoch integer
---@return boolean released
function CompilerPool:releaseBootSourceHold(epoch)
  local selected = self.selected
  if self.bootSourceHold ~= true or selected == nil then
    return false
  end
  if type(epoch) ~= "number" or epoch ~= selected.epoch then
    return false
  end
  self.bootSourceHold = nil
  self:_maybeReleaseSource()
  return true
end

-- Reply source-unavailable to every worker currently waiting on a buffer
-- and forget them. Their suspended jobs settle as failed with the typed
-- cause through the ordinary completion path, which frees their slots; no
-- waiter is left behind on quiescence, retirement, or reselection.
---@param failure table<string, unknown> plain typed error
function CompilerPool:_failSourceWaiters(failure)
  for workerId in pairs(self.sourceWaiters) do
    local worker = self.workers[workerId]
    local slot = worker ~= nil and worker.slot or nil
    if worker ~= nil and slot ~= nil then
      pcall(pushSourceUnavailable, self, worker, slot, failure)
    end
  end
  self.sourceWaiters = {}
end

-- Forget the selected buffer and every borrower without notifying: the
-- pool drops only its own reference while borrowed views stay readable
-- through their owners. Callers first fail or drain the waiters.
function CompilerPool:_dropSharedSource()
  self.sharedSource = nil
  self.sourceBorrowers = {}
  self.offeredSource = nil
end

-- Acquire the one immutable selected buffer: consume a verified ephemeral
-- offer first, otherwise load the registered external ROM through the
-- binding, verify it, convert it once to shared Data, and drop every
-- temporary byte string. Returns the buffer or nil plus a plain typed
-- error; a failure stores nothing and leaves prior receipts untouched.
---@param versionId string
---@return userdata? byteData
---@return table<string, unknown>? failure
function CompilerPool:_acquireSharedSource(versionId)
  local selected = assert(self.selected, "source acquisition requires its selection")
  local offered = self.offeredSource
  self.offeredSource = nil
  if
    offered ~= nil
    and offered.epoch == selected.epoch
    and offered.versionId == versionId
    and type(offered.byteData) == "userdata"
  then
    return offered.byteData
  end
  local RomBinding = require("romdump.src.source.RomBinding")
  local RomSource = require("romdump.src.source.RomSource")
  local NdsRom = require("romdump.src.source.NdsRom")
  local binding, bindErr = RomBinding.read(self:_cacheFsFor(versionId), versionId)
  if binding == nil then
    return nil, sourceErrorTable(bindErr)
  end
  if binding.path == false then
    return nil,
      sourceErrorTable(
        Errors.new(
          "ROM_SOURCE_REQUIRED",
          "no reopenable source is registered for version " .. versionId,
          { versionId = versionId }
        )
      )
  end
  local source, srcErr = RomSource.fromPath(
    binding.path,
    binding.kind == "zip" and type(binding.zipEntry) == "string" and { zipEntry = binding.zipEntry } or nil
  )
  if source == nil then
    return nil, sourceErrorTable(srcErr)
  end
  local rom, romErr = NdsRom.open(source)
  if rom == nil then
    source:release()
    return nil, sourceErrorTable(romErr)
  end
  local info = rom:versionInfo()
  if info.id ~= versionId or info.sha1:lower() ~= binding.romSha1:lower() then
    rom:release()
    return nil,
      sourceErrorTable(
        Errors.new(
          "ROM_SOURCE_MISMATCH",
          "the file at the registered source path does not match version " .. versionId,
          { versionId = versionId, path = binding.path }
        )
      )
  end
  local host = rawget(_G, "love")
  local dataApi = host and host.data
  if type(dataApi) ~= "table" or type(dataApi.newByteData) ~= "function" then
    rom:release()
    error("unsupported compiler pool capability: love.data.newByteData is required", 0)
  end
  local bytes, readErr = source:read(0, source:size())
  if bytes == nil then
    rom:release()
    return nil, sourceErrorTable(readErr)
  end
  local byteData = dataApi.newByteData(bytes)
  -- The pool retains only the shared buffer; every temporary Lua/ZIP byte
  -- string is dropped here so one selection never holds two copies.
  bytes = nil
  rom:release()
  return byteData
end

-- Handle one worker source request against its live physical slot. The slot
-- stays occupied through the wait: a request is a protocol transition, not
-- a completion. The first miss acquires once and every concurrent waiter
-- borrows the identical buffer; acquisition failures fan out as typed
-- source-unavailable to every waiter exactly once. A request that names no
-- live slot of the current selection is stale: it earns no buffer and no
-- new acquisition, and an unblocked stale waiter is released with a typed
-- unavailable instead of waiting forever.
---@param message table<string, unknown>
function CompilerPool:_acceptSourceNeeded(message)
  if type(message.workerId) ~= "number" then
    self:_stopWithProtocolFailure(message, "source request without a worker")
  end
  local worker = self.workers[message.workerId]
  local selected = self.selected
  local slot = worker ~= nil and worker.slot or nil
  local live = worker ~= nil
    and slot ~= nil
    and slot.jobKey == message.jobKey
    and slot.epoch == message.epoch
    and slot.generationId == message.generationId
    and (message.versionId == nil or slot.versionId == message.versionId)
    and selected ~= nil
    and not self.retired
    and slot.versionId == selected.versionId
    and slot.generationId == selected.generationId
    and slot.epoch == selected.epoch
  if not live then
    if worker ~= nil and type(message.epoch) == "number" and (slot == nil or slot.epoch == message.epoch) then
      local stale = slot
        or {
          jobKey = message.jobKey,
          versionId = selected ~= nil and selected.versionId or message.versionId,
          generationId = message.generationId,
          epoch = message.epoch,
        }
      pcall(
        pushSourceUnavailable,
        self,
        worker,
        stale --[[@as CompilerPool.Job]],
        sourceErrorTable(Errors.new("SOURCE_EPOCH_RETIRED", "source request does not match the live selection", {}))
      )
    end
    return
  end
  assert(worker, "live source request owns its worker")
  assert(slot, "live source request owns its slot")
  local held = self.sharedSource
  if held ~= nil then
    self.sourceBorrowers[worker.id] = true
    pushSourceSupply(self, worker, slot, held.byteData)
    return
  end
  self.sourceWaiters[worker.id] = true
  local byteData, acqErr = self:_acquireSharedSource(slot.versionId)
  if byteData ~= nil then
    self.sharedSource = {
      byteData = byteData,
      versionId = slot.versionId,
      generationId = slot.generationId,
      epoch = slot.epoch,
    }
    for waiterId in pairs(self.sourceWaiters) do
      local waiter = self.workers[waiterId]
      local waiterSlot = waiter ~= nil and waiter.slot or nil
      if waiter ~= nil and waiterSlot ~= nil then
        self.sourceBorrowers[waiterId] = true
        pushSourceSupply(self, waiter, waiterSlot, byteData)
      end
    end
    self.sourceWaiters = {}
    return
  end
  assert(acqErr, "a failed acquisition names its cause")
  local waiters = self.sourceWaiters
  self.sourceWaiters = {}
  for waiterId in pairs(waiters) do
    local waiter = self.workers[waiterId]
    local waiterSlot = waiter ~= nil and waiter.slot or nil
    if waiter ~= nil and waiterSlot ~= nil then
      pushSourceUnavailable(self, waiter, waiterSlot, acqErr)
    end
  end
end

---@param self CompilerPool
---@param priority integer
---@return CompilerPool.Node[] oldest live head per size class, oldest first
local function priorityHeads(self, priority)
  local heads = {}
  for _, sizeClass in ipairs(SIZE_ORDER) do
    local node = peekLane(self, priority, sizeClass)
    if node ~= nil then
      heads[#heads + 1] = node
    end
  end
  -- At most three heads: order explicitly without a general sort.
  for left = 2, #heads do
    local candidate = heads[left]
    local index = left
    while index > 1 and before(candidate, heads[index - 1]) do
      heads[index] = heads[index - 1]
      index = index - 1
    end
    heads[index] = candidate
  end
  return heads
end

-- Physical occupancy behind the interactive single background slot: any
-- worker holding a running or prepared-pinned job counts, whatever its
-- priority or epoch. Prepared results pin their worker until publication
-- drains them, so slots cover both states without consulting the queue.
---@param self CompilerPool
---@return boolean
local function backgroundSlotHeld(self)
  for _, worker in ipairs(self.workers) do
    if worker.slot ~= nil then
      return true
    end
  end
  return false
end

function CompilerPool:_eligibleRecord()
  if self.quiescing or self.queuedCount == 0 then
    return nil
  end
  if self:_runningCount() + #self.completions > #self.workers then
    return nil
  end
  local idle = false
  for _, worker in ipairs(self.workers) do
    if workerIdle(worker) then
      idle = true
      break
    end
  end
  if not idle then
    return nil
  end
  for _, priority in ipairs(PRIORITIES) do
    -- Interactive background work keeps a single physical slot: while any
    -- worker holds a running or prepared-pinned job, no non-required job
    -- may dispatch. Required work stays exempt and takes any free worker
    -- without preempting the held slot.
    if self.mode == "interactive" and priority ~= 0 and backgroundSlotHeld(self) then
      return nil
    end
    for _, node in ipairs(priorityHeads(self, priority)) do
      local record = self.jobs[node.key]
      if record ~= nil and record.node == node and record.state == "queued" then
        return record
      end
    end
  end
  return nil
end

---@return string "runnable" when pool work can advance now, "waiting" while progress needs an external compiler or close result, else "idle"
function CompilerPool:activityState()
  -- Read-only projection over bounded physical facts for the controller
  -- drive: a fatal condition surfaces through the next pump, a queued
  -- reply or prepared publication advances locally, dispatch eligibility
  -- stays with the single admission authority, and only occupied slots,
  -- held-back queues, or unacknowledged close barriers count as external
  -- waits. Retained job history is never scanned and nothing is consumed.
  if self.fatalError ~= nil then
    return "runnable"
  end
  if self.resultChannel:getCount() > 0 then
    return "runnable"
  end
  if #self.completions > 0 then
    return "runnable"
  end
  if self:_eligibleRecord() ~= nil then
    return "runnable"
  end
  for _, worker in ipairs(self.workers) do
    if worker.slot ~= nil then
      return "waiting"
    end
  end
  -- An unacknowledged source-release close resolves on the pool-private
  -- result channel, so the controller must keep polling instead of
  -- blocking on its control channel while one is outstanding.
  for _, worker in ipairs(self.workers) do
    if worker.srcCloseToken ~= nil and not worker.joined then
      return "waiting"
    end
  end
  if self.queuedCount > 0 then
    return "waiting"
  end
  for _, worker in ipairs(self.workers) do
    if worker.closeSent and not worker.closeAcked and not worker.joined then
      return "waiting"
    end
  end
  return "idle"
end

---@return CompilerPool.Worker?
function CompilerPool:_idleWorkerFor()
  for _, worker in ipairs(self.workers) do
    if workerIdle(worker) then
      return worker
    end
  end
  return nil
end

function CompilerPool:_dispatch()
  while true do
    local record = self:_eligibleRecord()
    if not record then
      return
    end
    local worker = self:_idleWorkerFor()
    if not worker then
      return
    end
    assert(record.node ~= nil, "queued compiler job is missing its queue position")
    claimLane(self, record.node)
    record.node = nil
    self.queuedCount = self.queuedCount - 1
    assert(self.queuedCount >= 0, "queued compiler jobs never dispatch twice")
    self.sequence = self.sequence + 1
    self.dispatchSequence = self.dispatchSequence + 1
    local dispatchId = self.dispatchSequence
    local dependencies = self:_dependencyView(record)
    record.state = "running"
    record.dispatchId = dispatchId
    record.workerId = worker.id
    worker.slot = record
    local ok, pushError = pcall(worker.input.push, worker.input, {
      kind = record.kind,
      key = record.key,
      jobKey = record.jobKey,
      versionId = record.versionId,
      generationId = record.generationId,
      epoch = record.epoch,
      sizeClass = record.sizeClass,
      payload = record.payload,
      producerFingerprint = record.payload.producerFingerprint,
      mapId = record.payload.mapId,
      matrixMemberId = record.payload.matrixMemberId,
      index = record.payload.index,
      x = record.payload.x,
      z = record.payload.z,
      mapHeaderId = record.payload.mapHeaderId,
      altitude = record.payload.altitude,
      landDataMemberId = record.payload.landDataMemberId,
      areaDataMemberId = record.payload.areaDataMemberId,
      memberId = record.payload.memberId,
      generationKey = record.payload.generationKey,
      bankId = record.payload.bankId,
      pageKind = record.payload.pageKind,
      pageId = record.payload.pageId,
      dispatchId = dispatchId,
      dependencies = dependencies,
    })
    if not ok then
      worker.slot = nil
      record.state = "failed"
      record.details = { error = pushError }
      record.dispatchId = nil
      record.workerId = nil
      self.fatalError = pushError
      error(pushError, 0)
    end
  end
end

function CompilerPool:_settleFailure(record, workerId, failure)
  record.state = "failed"
  record.details = { workerId = workerId, error = failure }
end

---@param message table<string, unknown>
---@param reason string
---@noreturn
function CompilerPool:_stopWithProtocolFailure(message, reason)
  local failure = "compiler protocol failure: " .. reason
  if type(message) == "table" and message.jobKey ~= nil then
    failure = failure .. " for " .. tostring(message.jobKey)
  end
  self.fatalError = failure
  error(failure, 0)
end

---@param record CompilerPool.Job
---@param message table<string, unknown>
function CompilerPool:_readFailure(record, message)
  -- A pool-reported source failure carries its typed cause on the completion
  -- itself; the coded cause must reach the session textually instead of
  -- collapsing to a generic fault.
  if type(message.error) == "table" and type(message.error.code) == "string" then
    local restored = sourceErrorTable(message.error)
    -- Render through the structured formatter so diagnostic context (the
    -- conflicting shared path, for example) survives instead of being
    -- dropped: an empty context renders exactly the bare code and message.
    local failure = Errors.format(Errors.new(restored.code, tostring(restored.message), restored.context))
    if type(message.error.traceback) == "string" and message.error.traceback ~= "" then
      failure = failure .. "\n" .. message.error.traceback
    end
    self:_settleFailure(record, message.workerId, failure)
    return
  end
  local failure = "worker failed" ---@type string|Errors.Error
  if type(message.error) == "string" and message.error ~= "" then
    failure = message.error
  else
    failure = restoreError(failure)
  end
  self:_settleFailure(record, message.workerId, failure)
end

---@param message table<string, unknown>
---@return table<string, unknown>
local function messageIdentity(message)
  return {
    workerId = message.workerId,
    dispatchId = message.dispatchId,
    epoch = message.epoch,
    generationId = message.generationId,
    kind = message.kind,
    key = message.key,
    jobKey = message.jobKey,
  }
end

---@param message table<string, unknown>
function CompilerPool:_acceptMessage(message)
  if type(message) == "table" and message.status == "context-closed" then
    local worker = self.workers[message.workerId]
    -- Only a matching barrier token proves source closure. Stale tokens
    -- from an earlier barrier and unknown senders are ignored, never
    -- mistaken for closure of the current barrier. A quiescence ack also
    -- proves the worker's borrowed source view closed, so it releases the
    -- borrower alongside the barrier.
    if worker ~= nil and worker.closeSent and message.closeToken == worker.closeToken then
      worker.closeAcked = true
      self.sourceBorrowers[worker.id] = nil
      self.sourceReleaseWait[worker.id] = nil
    end
    if worker ~= nil and worker.srcCloseToken ~= nil and message.closeToken == worker.srcCloseToken then
      worker.srcCloseToken = nil
      self.sourceBorrowers[worker.id] = nil
      self.sourceReleaseWait[worker.id] = nil
    end
    self:_completeSourceRelease()
  elseif type(message) == "table" and message.status == "source-needed" then
    self:_acceptSourceNeeded(message)
  elseif
    type(message) == "table"
    and (message.status == "prepared" or message.status == "failed" or message.status == "images-pending")
  then
    self:_acceptCompletion(message)
  else
    self:_stopWithProtocolFailure(message, "unknown worker message")
  end
end

function CompilerPool:_drainAvailable()
  while true do
    local message = self.resultChannel:pop()
    if message == nil then
      break
    end
    self:_acceptMessage(message)
  end
end

function CompilerPool:_collectResults()
  self:_drainAvailable()
end

-- A slot is obsolete once its job leaves the selected generation's lookup or
-- the selection is retired: its terminal reply must settle without publishing.
---@param slot CompilerPool.Job
---@return boolean
function CompilerPool:_slotObsolete(slot)
  if self.jobs[slot.jobKey] ~= slot then
    return true
  end
  local selected = self.selected
  if selected == nil or self.retired then
    return true
  end
  return slot.generationId ~= selected.generationId
    or slot.epoch ~= selected.epoch
    or slot.versionId ~= selected.versionId
end

-- Record that one attempt settled on its worker. Dispatch identities are
-- process-local and monotonic, so the highest settled identity is enough to
-- recognise a repeat of an already released attempt.
---@param worker CompilerPool.Worker
---@param record CompilerPool.Job
local function markSettled(worker, record)
  local dispatchId = record.dispatchId
  if type(dispatchId) == "number" and dispatchId > (worker.settledThrough or 0) then
    worker.settledThrough = dispatchId
  end
end

-- One attempt's terminal outcome is recorded once. A completion that repeats
-- the recorded outcome of its own dispatch attempt settles nothing new; a
-- different outcome for that same attempt is an invariant error.
---@param slot CompilerPool.Job
---@param message table<string, unknown>
---@return boolean repeats
local function repeatsSettledOutcome(slot, message)
  if slot.state == "cancelled" then
    return true
  end
  local details = slot.details
  if type(details) ~= "table" then
    return false
  end
  if message.status == "failed" then
    return slot.state == "failed"
  end
  local result = details.result
  return slot.state == "ready" and type(result) == "table" and result.marker == message.marker
end

---@param message table<string, unknown>
function CompilerPool:_acceptCompletion(message)
  assert(type(message) == "table", "worker completion must be a table")
  local workerId = message.workerId
  local worker = self.workers[workerId]
  if type(workerId) ~= "number" or not worker then
    self:_stopWithProtocolFailure(message, "unknown worker")
  end
  assert(worker, "compiler worker is required")
  local slot = worker.slot
  if not slot then
    -- A repeat of an attempt that already settled on this worker is dropped
    -- with its own references: its outcome is recorded and cannot change.
    local settledThrough = worker.settledThrough or 0
    if type(message.dispatchId) == "number" and message.dispatchId <= settledThrough then
      return
    end
    self:_stopWithProtocolFailure(message, "duplicate completion for an idle worker")
  end
  assert(slot, "compiler worker slot is required")
  local identity = messageIdentity(message)
  if identity.workerId ~= worker.id then
    self:_stopWithProtocolFailure(message, "completion does not match its worker slot")
  end
  -- A result that answers an attempt this worker no longer owns belongs to a
  -- settled or retired attempt: it can change nothing and is dropped with its
  -- own references, never mistaken for the live attempt's outcome.
  if identity.dispatchId ~= slot.dispatchId then
    return
  end
  if
    identity.epoch ~= slot.epoch
    or identity.generationId ~= slot.generationId
    or identity.kind ~= slot.kind
    or identity.key ~= slot.key
    or identity.jobKey ~= slot.jobKey
  then
    self:_stopWithProtocolFailure(message, "completion does not match its worker slot")
  end
  -- The parent's authored output is held by its pending PNG continuation,
  -- which owns the slot until it returns the sealed output or reports that the
  -- encode failed. A repeat of the earlier image packet (however late) cannot
  -- settle it a second time.
  if slot.state == "images" and message.status == "images-pending" then
    return
  end
  if
    slot.state ~= "running"
    and not (slot.state == "images" and (message.status == "prepared" or message.status == "failed"))
  then
    -- The same attempt's settlement is recorded once: an exact repeat of it
    -- is idempotent, while a conflicting result for that attempt stays an
    -- invariant error.
    if repeatsSettledOutcome(slot, message) then
      return
    end
    self:_stopWithProtocolFailure(message, "worker completed an already-settled job")
  end
  local obsolete = self:_slotObsolete(slot)
  -- One prepared unpublished result per physical worker: the worker stays
  -- pinned until its result is committed, failed, or otherwise authoritatively
  -- settled. Logical cancellation never frees a running slot; retirement only
  -- invalidates interest.
  local function release()
    markSettled(worker, slot)
    worker.slot = nil
    if worker.closeAfter then
      self:_sendCloseContext(worker)
    end
  end
  if message.status == "failed" then
    -- An abandoned PNG continuation drops its parent's private output and any
    -- remaining RGBA interests with the packet that carried them.
    slot.pending = nil
    release()
    if obsolete then
      slot.state = "cancelled"
      return
    end
    self:_readFailure(slot, message)
    self:_recordTiming(slot, message)
    return
  end
  if obsolete then
    release()
    slot.state = "cancelled"
    return
  end
  if message.status == "images-pending" then
    -- The authored output waits in this worker for its own low-priority PNG
    -- continuation: pin the slot, remember the packet, and send the same
    -- worker the encoder task. Nothing is published until it returns.
    local packet = {
      generationId = slot.generationId,
      epoch = slot.epoch,
      kind = slot.kind,
      key = slot.key,
      jobKey = slot.jobKey,
      marker = message.marker,
      ownedRoots = message.ownedRoots,
      sharedPaths = message.sharedPaths,
      entries = message.entries,
      images = message.images,
    }
    assert(type(packet.images) == "table" and #packet.images > 0, "an image packet carries its pending pixels")
    slot.state = "images"
    slot.pending = packet
    self:_recordTiming(slot, message)
    local ok, pushError = pcall(worker.input.push, worker.input, {
      kind = "encode-png",
      workerId = worker.id,
      dispatchId = slot.dispatchId,
      versionId = slot.versionId,
      generationId = slot.generationId,
      epoch = slot.epoch,
      jobKey = slot.jobKey,
      parentKind = slot.kind,
      key = slot.key,
      priority = ArtifactJobs.priorityFor("sweep"),
      dependencies = self:_dependencyView(slot),
      pending = packet,
      workSeconds = message.workSeconds,
    })
    if not ok then
      slot.pending = nil
      self:_settleFailure(slot, worker.id, tostring(pushError))
      self:_freeSlot(slot, worker.id)
    end
    return
  end
  assert(message.status == "prepared", "worker completion must be a sealed result")
  slot.state = "prepared"
  slot.pending = nil
  self:_recordTiming(slot, message)
  self.completions[#self.completions + 1] = {
    record = slot,
    workerId = worker.id,
    result = {
      marker = message.marker,
      ownedRoots = message.ownedRoots,
      sharedPaths = message.sharedPaths,
      entries = message.entries,
    },
  }
  -- The worker's terminal reply arrived: its source context may close even
  -- while the pool-side pin holds the slot until publication drains the
  -- result. Compilation is complete, so closing races nothing.
  if worker.closeAfter then
    self:_sendCloseContext(worker)
  end
end

---@param record CompilerPool.Job
---@param message table<string, unknown>
function CompilerPool:_recordTiming(record, message)
  record.timing = {
    compileSeconds = message.compileSeconds,
    stageSeconds = message.stageSeconds,
    workSeconds = message.workSeconds,
    stagedBytes = message.stagedBytes,
    timingReason = message.timingReason,
  }
end

---@param worker CompilerPool.Worker
function CompilerPool:_sendCloseContext(worker)
  if worker.closeSent or not worker.started or worker.joined then
    return
  end
  assert(self.closeToken ~= nil, "compiler pool close barrier identity is required")
  local token = self.closeToken
  local ok, sendError = pcall(worker.input.push, worker.input, { kind = "close-context", closeToken = token })
  if not ok then
    self.fatalError = sendError
    error(sendError, 0)
  end
  worker.closeSent = true
  worker.closeToken = token
end

---@param worker CompilerPool.Worker
function CompilerPool:_sendSourceClose(worker)
  if worker.srcCloseToken ~= nil or not worker.started or worker.joined then
    return
  end
  -- String tokens never collide with the numeric quiescence barrier, so a
  -- source-release acknowledgement is never mistaken for barrier closure.
  self.sourceCloseSeq = self.sourceCloseSeq + 1
  local token = "src-" .. tostring(self.sourceCloseSeq)
  local ok, sendError = pcall(worker.input.push, worker.input, { kind = "close-context", closeToken = token })
  if not ok then
    self.fatalError = sendError
    error(sendError, 0)
  end
  worker.srcCloseToken = token
end

-- Complete a started release round once every member acknowledged: workers
-- that borrowed again after the decision get a courtesy close so no view
-- outlives the pool reference unnoticed, then the pool reference drops. A
-- later miss reacquires once. Borrowed views stay readable through their
-- owners throughout; only the pool stops pinning the buffer.
function CompilerPool:_completeSourceRelease()
  if self.sharedSource == nil or not self.sourceReleaseOpen then
    return
  end
  if next(self.sourceReleaseWait) ~= nil then
    return
  end
  self.sourceReleaseOpen = false
  for waiterId in pairs(self.sourceBorrowers) do
    local worker = self.workers[waiterId]
    if worker ~= nil and not worker.joined and not worker.closeSent then
      self.sourceCloseSeq = self.sourceCloseSeq + 1
      pcall(
        worker.input.push,
        worker.input,
        { kind = "close-context", closeToken = "src-drop-" .. tostring(self.sourceCloseSeq) }
      )
    end
  end
  self:_dropSharedSource()
  for _, worker in ipairs(self.workers) do
    worker.srcCloseToken = nil
  end
end

-- Release the selected buffer once no pool work can still need it: no
-- queued interest, no running or prepared record, no occupied slot, and no
-- pending publication. The borrowers at the decision form one release
-- round; later re-borrows do not join it. The pool-held reference drops
-- when the round fully acknowledges (or joined exits prove closure), even
-- if new interest arrived meanwhile: correctness of the close barrier
-- matters, not holding the buffer across quiet moments.
function CompilerPool:_maybeReleaseSource()
  if self.sharedSource == nil then
    return
  end
  -- A joined exit proves closure without an acknowledgement.
  for waiterId in pairs(self.sourceBorrowers) do
    local worker = self.workers[waiterId]
    if worker == nil or worker.joined then
      self.sourceBorrowers[waiterId] = nil
    end
  end
  for waiterId in pairs(self.sourceReleaseWait) do
    local worker = self.workers[waiterId]
    if worker == nil or worker.joined then
      self.sourceReleaseWait[waiterId] = nil
    end
  end
  if self.sourceReleaseOpen then
    self:_completeSourceRelease()
    return
  end
  -- A boot-held buffer survives the pre-sweep gap even with zero
  -- borrowers: only attestation release, retirement, quiescence, or
  -- shutdown may drop it. This check precedes the borrower-free shortcut
  -- below, which otherwise releases an idle buffer before future sweep
  -- work the pool cannot see.
  if self.bootSourceHold == true then
    return
  end
  if next(self.sourceBorrowers) == nil then
    -- Nobody left to ask: every closure was already proven through another
    -- barrier, so the idle reference drops at once.
    self:_dropSharedSource()
    for _, worker in ipairs(self.workers) do
      worker.srcCloseToken = nil
    end
    return
  end
  if self.queuedCount > 0 or #self.completions > 0 then
    return
  end
  for _, record in pairs(self.jobs) do
    if
      record.state == "running"
      or record.state == "prepared"
      or record.state == "images"
      or record.state == "queued"
    then
      return
    end
  end
  for _, worker in ipairs(self.workers) do
    if worker.slot ~= nil then
      return
    end
  end
  -- The sweep owns future source work the pool cannot see: when a
  -- generation session installed its settled oracle, an idle pool holds
  -- the buffer across sweep gaps instead of releasing and reacquiring
  -- it. Without an oracle (standalone pool use) idleness alone decides.
  -- An already-open release round and the borrower-free fast path above
  -- stay ungated: barrier completion must never stall on future work.
  if type(self.sourceSettledQuery) == "function" and not self.sourceSettledQuery() then
    return
  end
  self.sourceReleaseOpen = true
  for waiterId in pairs(self.sourceBorrowers) do
    self.sourceReleaseWait[waiterId] = true
    local worker = self.workers[waiterId]
    if worker ~= nil and not worker.joined and worker.srcCloseToken == nil and not worker.closeSent then
      self:_sendSourceClose(worker)
    end
  end
end

function CompilerPool:_pollWorkerFailures()
  local slotSuspects = {}
  local idleSuspects = {}
  for _, worker in ipairs(self.workers) do
    if not worker.joined and worker.started then
      local errorText = worker.thread:getError()
      local dead = type(worker.thread.isRunning) == "function" and not worker.thread:isRunning()
      if errorText or dead then
        if worker.slot ~= nil then
          slotSuspects[#slotSuspects + 1] = { worker = worker, slot = worker.slot }
        else
          idleSuspects[#idleSuspects + 1] = worker
        end
      end
    end
  end
  if #slotSuspects == 0 and #idleSuspects == 0 then
    return
  end
  -- A terminal reply queued ahead of its sender's exit is accepted here,
  -- before any dead observation below may classify that sender.
  self:_drainAvailable()
  for _, suspect in ipairs(slotSuspects) do
    local worker = suspect.worker
    -- Recheck the original physical slot: a later replacement or job must
    -- never inherit this dead observation.
    if
      self.workers[worker.id] == worker
      and worker.slot == suspect.slot
      and (suspect.slot.state == "running" or suspect.slot.state == "images")
    then
      local errorText = worker.thread:getError()
      local dead = type(worker.thread.isRunning) == "function" and not worker.thread:isRunning()
      if errorText or dead then
        local record = suspect.slot
        local failure = errorText or "compiler worker stopped unexpectedly"
        self:_settleFailure(record, worker.id, failure)
        worker.slot = nil
        self.fatalError = failure
      end
    end
  end
  for _, worker in ipairs(idleSuspects) do
    if self.workers[worker.id] == worker and worker.slot == nil and not worker.joined then
      local errorText = worker.thread:getError()
      local dead = type(worker.thread.isRunning) == "function" and not worker.thread:isRunning()
      if errorText or dead then
        local failure
        if worker.closeSent and not worker.closeAcked then
          failure = "compiler source close failed: " .. tostring(errorText or "compiler worker stopped unexpectedly")
        else
          failure = errorText or "compiler worker stopped unexpectedly"
        end
        pcall(worker.thread.wait, worker.thread)
        worker.joined = true
        self.fatalError = failure
      end
    end
  end
end

---@param committed love.Data
---@param staged love.Data
---@return boolean
local function sameBytes(committed, staged)
  return committed:getSize() == staged:getSize() and committed:getString() == staged:getString()
end

-- The single memory publisher: one prepared worker result becomes a visible
-- byte/fact commit. One logical path resolves to one committed payload here,
-- against already committed bytes, because only this serialized point sees two
-- producers' output for one path. Both the batch and the fact are prepared
-- before either becomes visible, and the two commits run without yielding.
---@param record CompilerPool.Job
---@param result table<string, unknown>
---@return ArtifactState.Fact
function CompilerPool:_commitArtifact(record, result)
  local store = assert(self.store, "compiler pool has no committed store")
  local facts = assert(self.facts, "compiler pool has no committed facts")
  local selected = assert(self.selected, "compiler pool has no selection")
  assert(record.versionId == selected.versionId, "artifact commit does not match the selected version")
  assert(record.generationId == selected.generationId, "artifact commit does not match the selected generation")
  assert(record.epoch == selected.epoch, "artifact commit does not match the selected epoch")
  assert(type(result.marker) == "string" and result.marker ~= "", "artifact commit carries no marker")
  assert(type(result.sharedPaths) == "table", "artifact commit carries no shared declarations")
  local batch = {}
  local files = {}
  for _, entry in ipairs(assert(result.entries, "artifact commit carries no output entries")) do
    -- A path two artifacts publish is one payload whether each artifact owns
    -- it or declares it shared: equal bytes reuse the committed Data, a
    -- contradiction refuses this artifact, and only a pixel-identical PNG
    -- reinstalls its staged bytes.
    local committed = store:resolveAsset(entry.path)
    if committed == nil then
      batch[#batch + 1] = entry
    elseif not PreparedArtifact.equalContent(entry.path, committed.data, entry.data) then
      Errors.raise("PREPARED_SHARED_CONFLICT", "staged output contradicts the committed artifact", {
        path = entry.path,
      })
    elseif not sameBytes(committed.data, entry.data) then
      batch[#batch + 1] = entry
    end
    files[#files + 1] = { path = entry.path, size = entry.data:getSize() }
  end
  local wanted = {}
  for _, entry in ipairs(batch) do
    wanted[#wanted + 1] = {
      path = entry.path,
      data = entry.data,
      size = entry.data:getSize(),
      sourceId = store:sourceId(),
      contentId = record.generationId .. "\0" .. entry.path,
    }
  end
  local prepared = store:prepare(wanted)
  local dependencyKeys = {}
  for _, dependency in ipairs(record.dependencies) do
    dependencyKeys[#dependencyKeys + 1] = ArtifactState.key(dependency.kind, dependency.key)
  end
  local fact = ArtifactState.prepareFact({
    kind = record.kind,
    key = record.key,
    marker = result.marker,
    ownedRoots = result.ownedRoots or {},
    sharedPaths = result.sharedPaths,
    entries = files,
  }, dependencyKeys, facts)
  store:commit(prepared)
  ArtifactState.commitFact(facts, fact)
  self.publishedCommits = self.publishedCommits + 1
  return fact
end

function CompilerPool:_publishOne()
  local completion = table.remove(self.completions, 1)
  if not completion then
    return false
  end
  local record = completion.record
  if record.state ~= "prepared" then
    self:_freeSlot(record, completion.workerId)
    return true
  end
  local ok, factOrFailure = pcall(self._commitArtifact, self, record, completion.result)
  if not ok then
    self:_settleFailure(record, completion.workerId, factOrFailure)
  else
    local fact = factOrFailure --[[@as ArtifactState.Fact]]
    record.state = "ready"
    record.details = {
      workerId = completion.workerId,
      result = { marker = fact.marker },
    }
    self.recentTimings[#self.recentTimings + 1] = {
      jobKey = record.jobKey,
      workerId = completion.workerId,
      compileSeconds = record.timing and record.timing.compileSeconds,
      stageSeconds = record.timing and record.timing.stageSeconds,
      workSeconds = record.timing and record.timing.workSeconds,
      stagedBytes = record.timing and record.timing.stagedBytes,
      timingReason = record.timing and record.timing.timingReason,
    }
    if #self.recentTimings > MAX_RECENT_TIMINGS then
      table.remove(self.recentTimings, 1)
    end
  end
  self:_freeSlot(record, completion.workerId)
  return true
end

---@param record CompilerPool.Job
---@param workerId integer
function CompilerPool:_freeSlot(record, workerId)
  local worker = self.workers[workerId]
  if worker and worker.slot == record then
    markSettled(worker, record)
    worker.slot = nil
    if worker.closeAfter then
      self:_sendCloseContext(worker)
    end
  else
    for _, other in ipairs(self.workers) do
      if other.slot == record then
        markSettled(other, record)
        other.slot = nil
        if other.closeAfter then
          self:_sendCloseContext(other)
        end
        break
      end
    end
  end
end

---@param budget number?
function CompilerPool:update(budget)
  assert(not self.closed, "compiler pool is shut down")
  if self.fatalError then
    error(self.fatalError, 0)
  end
  -- Collect worker reports before polling liveness so a completion that
  -- arrived ahead of its worker's exit is accepted on its slot instead of
  -- being mistaken for a death.
  self:_collectResults()
  self:_pollWorkerFailures()
  if self.fatalError then
    error(self.fatalError, 0)
  end
  local remaining = budget
  if remaining == nil then
    remaining = PUBLICATION_BUDGET
  end
  assert(type(remaining) == "number", "publication budget must be a number")
  while remaining > 0 and self:_publishOne() do
    remaining = remaining - 1
  end
  self:_dispatch()
  self:_maybeReleaseSource()
  if self.fatalError then
    error(self.fatalError, 0)
  end
end

function CompilerPool:_hasUnsettled()
  if self.queuedCount > 0 or #self.completions > 0 then
    return true
  end
  for _, record in pairs(self.jobs) do
    if record.state == "running" or record.state == "prepared" or record.state == "images" then
      return true
    end
  end
  for _, worker in ipairs(self.workers) do
    if worker.slot ~= nil then
      return true
    end
  end
  return false
end

function CompilerPool:_waitForResult()
  self:_drainAvailable()
  if self.fatalError then
    error(self.fatalError, 0)
  end
  -- A reply returned by the bounded wait is accepted through the same
  -- validator as nonblocking collection, never pushed back onto the queue.
  local message = self.resultChannel:demand(WAIT_TIMEOUT_SECONDS)
  if message ~= nil then
    self:_acceptMessage(message)
  end
  self:_pollWorkerFailures()
  if self.fatalError then
    error(self.fatalError, 0)
  end
end

---@param jobKey string
---@return string
---@return table<string, unknown>?
function CompilerPool:wait(jobKey)
  assert(not self.closed, "compiler pool is shut down")
  local record = assert(self.jobs[jobKey], "unknown compiler job: " .. tostring(jobKey))
  while record.state ~= "ready" and record.state ~= "failed" and record.state ~= "cancelled" do
    if self.fatalError then
      error(self.fatalError, 0)
    end
    self:update(math.huge)
    if record.state ~= "ready" and record.state ~= "failed" and record.state ~= "cancelled" then
      self:_waitForResult()
    end
  end
  return record.state, record.details
end

function CompilerPool:waitForProgress()
  assert(not self.closed, "compiler pool is shut down")
  self:_waitForResult()
  if self.fatalError then
    error(self.fatalError, 0)
  end
  -- Bounded publication only: never dispatch new work here, and never admit
  -- after retirement or quiescence. Synchronous session callers use this to
  -- drive dependency progress without naming a submitted parent.
  local remaining = PUBLICATION_BUDGET
  while remaining > 0 and self:_publishOne() do
    remaining = remaining - 1
  end
  if self.fatalError then
    error(self.fatalError, 0)
  end
end

function CompilerPool:drain()
  assert(not self.closed, "compiler pool is shut down")
  self:_dispatch()
  while self:_hasUnsettled() do
    self:update(math.huge)
    if self:_hasUnsettled() then
      self:_waitForResult()
    end
  end
  return true
end

function CompilerPool:quiesce()
  assert(not self.closed, "compiler pool is shut down")
  if self.quiescing and self:isQuiescent() then
    return
  end
  -- A quiescing pool takes no new source interest: suspended waiters
  -- settle as failed with a typed cause so the barrier can complete.
  self:_failSourceWaiters(
    sourceErrorTable(Errors.new("SOURCE_EPOCH_RETIRED", "the compiler pool quiesced while source was awaited", {}))
  )
  -- Quiescence overrides the boot hold: retirement barriers govern the
  -- remaining lifetime from here.
  self.bootSourceHold = nil
  self.quiescing = true
  self.closeToken = (self.closeToken or 0) + 1
  for _, record in pairs(self.jobs) do
    if record.state == "queued" then
      record.state = "cancelled"
      record.node = nil
    end
  end
  resetLanes(self)
  for _, worker in ipairs(self.workers) do
    if worker.joined then
      -- An exited, joined worker needs no acknowledgement: its exit proves
      -- its source context is closed.
    elseif worker.slot == nil then
      worker.closeSent = false
      worker.closeAcked = false
      self:_sendCloseContext(worker)
    else
      worker.closeAfter = true
    end
  end
end

---@return boolean
function CompilerPool:isQuiescent()
  if not self.quiescing then
    return false
  end
  if self.fatalError ~= nil then
    return false
  end
  if self.queuedCount > 0 or #self.completions > 0 then
    return false
  end
  for _, record in pairs(self.jobs) do
    if
      record.state == "running"
      or record.state == "prepared"
      or record.state == "images"
      or record.state == "queued"
    then
      return false
    end
  end
  for _, worker in ipairs(self.workers) do
    if worker.joined then
      -- Joined exit satisfies closure without an acknowledgement.
    elseif worker.slot ~= nil then
      return false
    elseif not worker.closeAcked then
      return false
    end
  end
  return true
end

---@return table<string, unknown>
function CompilerPool:diagnostics()
  local counts = { queued = 0, running = 0, prepared = 0, images = 0, ready = 0, failed = 0, cancelled = 0 }
  local sizes = { normal = 0, heavy = 0, jumbo = 0 }
  local active = {}
  for _, record in pairs(self.jobs) do
    if counts[record.state] ~= nil then
      counts[record.state] = counts[record.state] + 1
    end
    if sizes[record.sizeClass] ~= nil then
      sizes[record.sizeClass] = sizes[record.sizeClass] + 1
    end
    if record.state == "running" or record.state == "prepared" or record.state == "images" then
      active[#active + 1] = record.jobKey
    end
  end
  table.sort(active)
  local selected = nil
  if self.selected then
    selected = {
      versionId = self.selected.versionId,
      generationId = self.selected.generationId,
      epoch = self.selected.epoch,
    }
  end
  local workerStates = {}
  for _, worker in ipairs(self.workers) do
    if worker.slot ~= nil then
      workerStates[#workerStates + 1] = "w" .. tostring(worker.id) .. ":busy"
    end
  end
  local heapStates = {}
  local queuedSeen = 0
  for _, priority in ipairs(PRIORITIES) do
    for _, sizeClass in ipairs(SIZE_ORDER) do
      local lane = self.lanes[priority][sizeClass]
      for index = lane.head, #lane.items do
        local node = lane.items[index]
        local record = self.jobs[node.key]
        if record ~= nil and record.node == node and record.state == "queued" then
          queuedSeen = queuedSeen + 1
          if queuedSeen <= 12 then
            heapStates[#heapStates + 1] = tostring(record.state) .. ":" .. tostring(record.sizeClass)
          end
        end
      end
    end
  end
  if queuedSeen > 12 then
    heapStates[#heapStates + 1] = "+" .. tostring(queuedSeen - 12) .. " more"
  end
  return {
    mode = self.mode,
    selected = selected,
    quiescing = self.quiescing,
    workerCount = #self.workers,
    counts = counts,
    sizes = sizes,
    activeJobKeys = active,
    workerStates = #workerStates > 0 and table.concat(workerStates, ",") or "idle",
    heapStates = table.concat(heapStates, ","),
    pendingPublications = #self.completions,
    error = self.fatalError,
    recentTimings = self.recentTimings,
  }
end

function CompilerPool:shutdown()
  if self.closed then
    return true
  end
  self.sourceWaiters = {}
  self:_dropSharedSource()
  self.sourceReleaseWait = {}
  self.sourceReleaseOpen = false
  self.bootSourceHold = nil
  for _, record in pairs(self.jobs) do
    if record.state == "queued" then
      record.state = "cancelled"
      record.node = nil
    end
  end
  resetLanes(self)
  for _, worker in ipairs(self.workers) do
    if worker.started and not worker.joined then
      pcall(worker.input.push, worker.input, { kind = "stop" })
    end
  end
  -- A proved shutdown joins every started worker: a failed wait leaves
  -- its worker unjoined and fails the shutdown without hiding the other
  -- joins, so no later call can claim success until the join genuinely
  -- completes. Staging teardown below runs only after every join proved.
  local joinError = nil
  for _, worker in ipairs(self.workers) do
    if worker.started and not worker.joined then
      local waited, failure = pcall(worker.thread.wait, worker.thread)
      if waited then
        worker.joined = true
      elseif joinError == nil then
        joinError = failure
      end
    end
  end
  if joinError ~= nil then
    error(joinError, 0)
  end
  pcall(function()
    self:_collectResults()
  end)
  while true do
    local ok, more = pcall(function()
      return self:_publishOne()
    end)
    if not ok or not more then
      break
    end
  end
  for _, worker in ipairs(self.workers) do
    if worker.slot ~= nil then
      local record = assert(worker.slot, "compiler worker slot is required")
      if record.state == "running" or record.state == "prepared" or record.state == "images" then
        record.state = "failed"
        record.details = { workerId = worker.id, error = "compiler worker stopped during shutdown" }
      end
      worker.slot = nil
    end
  end
  self:_closeCommittedGeneration()
  self.closed = true
  return true
end

return CompilerPool
