-- Explicit manual proof that one generation's derived cache is usable.
-- The audit walks the complete canonical inventory for the exact current
-- generation and checks every expected job through the dispatcher's
-- readiness validation: a committed artifact fact plus a usable payload.
-- Markers alone prove nothing, expected membership is never inferred from
-- whichever entries happen to exist, and the full-build attestation is
-- never consulted here. Ordinary warm reuse trusts committed facts and
-- the matching attestation without running this walk; only the explicit
-- check-derived-cache command invokes it. Read-only: no writes.

local ArtifactJobs = require("romdump.src.build.ArtifactJobs")
local ArtifactState = require("romdump.src.build.ArtifactState")

local DerivedCacheAudit = {}

---@param cacheFs CacheFs resident view over the committed generated bytes
---@param facts ArtifactState committed artifact facts for the same generation
---@param identity { versionId: string, generationId: string, producerId: string } current strict generation record
---@param plans ArtifactJobs.Plans complete published inventory for that exact identity
---@return boolean, string|nil
function DerivedCacheAudit.isAvailable(cacheFs, facts, identity, plans)
  assert(cacheFs and cacheFs.read and cacheFs.loadLua, "DerivedCacheAudit requires a generated reader")
  assert(type(facts) == "table" and type(facts.records) == "table", "DerivedCacheAudit requires the committed facts")
  assert(type(identity) == "table", "DerivedCacheAudit requires the current generation identity")
  local generationId = identity.generationId
  assert(type(generationId) == "string" and generationId ~= "", "DerivedCacheAudit requires a generation identity")
  assert(generationId == facts.generationId, "DerivedCacheAudit facts belong to another generation")
  assert(type(plans) == "table", "DerivedCacheAudit requires the complete source inventory")
  local jobsOk, jobs = pcall(ArtifactJobs.completeJobs, plans)
  if not jobsOk or type(jobs) ~= "table" then
    return false, "complete inventory is not available: " .. tostring(jobs)
  end
  ---@cast jobs { kind: string, key: string }[]
  for _, job in ipairs(jobs) do
    -- The fact read names absence precisely without duplicating family
    -- validation: a job without a committed fact fails here, and only a
    -- committed job reaches the payload check.
    if ArtifactState.read(facts, job.kind, job.key) == nil then
      return false, job.kind .. ":" .. job.key .. " has no committed artifact fact"
    end
    if not ArtifactJobs.validate(cacheFs, facts, job.kind, job.key, plans, identity) then
      return false, job.kind .. ":" .. job.key .. " fails its family validator"
    end
  end
  return true
end

return DerivedCacheAudit
