function T.gender_uses_two_bits_and_unused_low_rule_bits_do_not_match()
  local withStatus = string.rep("\0", 20)
  withStatus = setByte(withStatus, 2, 0xE9)
  withStatus = setByte(withStatus, 9, 0xA0)
  local withoutStatus = setByte(withStatus, 2, 0xC9)
  local lowBitsChanged = setByte(withStatus, 9, 0xBF)
  local first = Compiler.decodeRuleMember(withStatus)
  local second = Compiler.decodeRuleMember(withoutStatus)
  local third = Compiler.decodeRuleMember(lowBitsChanged)
  Assert.equal(first.criteria.genderClass, 1)
  Assert.equal(second.criteria.genderClass, first.criteria.genderClass)
  Assert.isNil(first.criteria.reservedReject)
  Assert.isNil(third.criteria.reservedReject)
  Assert.equal(third.criteria.facingClass, first.criteria.facingClass)
end

function T.program_steps_stop_at_ffff_and_preserve_signed_rewards_and_continuations()
  local bytes = u16(3)
    .. u16(0x123)
    .. u16(0x456)
    .. string.char(2, 2)
    .. u16(0xFFFF)
    .. string.rep("\0", 30)
    .. string.char(1, 0, 0, 0)
    .. u16(0x3FE)
    .. u16(0x2FD)
    .. string.char(0xFE, 0x03, 100, 5)
  local program = Compiler.decodeProgramMember(bytes)
  Assert.equal(#program.steps, 1)
  Assert.equal(program.steps[1].motionId, 3)
  Assert.equal(program.steps[1].messageId, 0x122)
  Assert.deepEqual(program.steps[1].sound, { kind = "effect", id = 0x456 })
  Assert.equal(program.steps[1].reactionId, 2)
  Assert.equal(program.steps[1].delayTicks, 2)
  Assert.equal(program.continuation.choice0InteractionId, 0x3FE)
  Assert.equal(program.continuation.choice1InteractionId, 0x2FD)
  Assert.equal(program.friendshipDelta, -2)
  Assert.equal(program.moodDelta, 3)
  Assert.equal(program.fashionAccessoryId, 99)
  Assert.equal(program.shinyLeafId, 5)
end

function T.program_steps_normalize_absent_motion_and_zero_based_messages()
  local bytes = u16(0) .. u16(0) .. u16(0) .. string.char(1, 0)
    .. u16(4) .. u16(8) .. u16(1) .. string.char(2, 0)
    .. u16(0xFFFF) .. string.rep("\0", 34)
  local program = Compiler.decodeProgramMember(bytes)
  Assert.equal(#program.steps, 2)
  Assert.isNil(program.steps[1].motionId)
  Assert.isNil(program.steps[1].messageId)
  Assert.equal(program.steps[2].motionId, 4)
  Assert.equal(program.steps[2].messageId, 7)
  Assert.isNil(program.steps[1].sound)
end

function T.program_steps_normalize_effect_and_cry_sound_boundaries()
  local function soundStep(sound)
    return u16(1) .. u16(1) .. u16(sound) .. string.char(1, 0)
  end
  local bytes = soundStep(0) .. soundStep(1) .. soundStep(2378) .. soundStep(2379)
    .. soundStep(2380) .. string.rep("\0", 12)
  local program = Compiler.decodeProgramMember(bytes)
  Assert.isNil(program.steps[1].sound)
  Assert.deepEqual(program.steps[2].sound, { kind = "effect", id = 1 })
  Assert.deepEqual(program.steps[3].sound, { kind = "effect", id = 2378 })
  Assert.deepEqual(program.steps[4].sound, { kind = "cry", pattern = 0 })
  Assert.deepEqual(program.steps[5].sound, { kind = "cry", pattern = 11 })
end

function T.motion_records_decode_signed_offsets_and_sound_presence_until_facing_ff()
  local record = string.char(2, 7, 0xFE, 3, 0x81, 1, 0xAA, 0x55)
  local motion = Compiler.decodeMotionMember(record .. string.char(0xFF) .. string.rep("\0", 71))
  Assert.equal(#motion, 1)
  Assert.equal(motion[1].facing, 2)
  Assert.equal(motion[1].ticks, 7)
  Assert.equal(motion[1].x, -0.125)
  Assert.equal(motion[1].y, 0.1875)
  Assert.equal(motion[1].z, -127 / 16)
  Assert.isTrue(motion[1].sound)
end

function T.reaction_descriptor_keeps_thresholds_and_unlabeled_selector_arrays()
  local bytes = u32(4) .. u16(0) .. u16(5) .. u16(9) .. u16(16) .. string.char(1, 2, 3, 4, 5, 6, 7, 8)
  local descriptor = Compiler.decodeReactionDescriptor(bytes)
  Assert.equal(#descriptor.keys, 4)
  Assert.equal(descriptor.keys[3].frame, 9)
  Assert.equal(descriptor.keys[4].texIdx, 4)
  Assert.equal(descriptor.keys[1].plttIdx, 5)
end

